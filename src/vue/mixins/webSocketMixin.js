// ============================================================
// webSocketMixin.js - WebSocket混入（学习版·Vue复用机制）
// ============================================================
// 
// 【文件职责】
// 提供WebSocket相关的Vue组件复用逻辑，包括：
// 1. 自动初始化WebSocket连接
// 2. 事件监听器管理
// 3. Vue生命周期集成
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. Vue Mixin：代码复用机制，将通用逻辑混入多个组件                      │
// │  2. 生命周期钩子：Mixin的钩子与组件钩子合并执行                          │
// │  3. 事件监听器管理：自动记录和清理，防止内存泄漏                         │
// │  4. localStorage/sessionStorage：读取用户信息                           │
// │  5. $socket：Vue原型上挂载的socket实例                                  │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【什么是Mixin？】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  Mixin 是 Vue 的一种代码复用机制                                        │
// │  可以把通用的属性、方法、生命周期钩子"混入"到多个组件中                  │
// │                                                                         │
// │  【合并规则】                                                            │
// │  - data: 合并，组件优先                                                  │
// │  - methods: 合并，组件优先                                               │
// │  - 生命周期钩子: 都执行，先Mixin后组件                                   │
// │                                                                         │
// │  【使用场景】                                                            │
// │  - 多个组件需要相同的WebSocket功能                                       │
// │  - 避免在每个组件中重复写初始化代码                                      │
// │  - 统一管理事件监听器的生命周期                                          │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【与socket.js的关系】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   socket.js（底层工具类）              webSocketMixin.js（Vue封装）     │
// │   ─────────────────────                ─────────────────────────        │
// │                                                                         │
// │   • 提供基本的连接和通信方法            • 自动初始化（读取用户信息）     │
// │   • 单例模式，全局共享                  • 事件监听器管理（自动清理）     │
// │   • 与框架无关                          • Vue生命周期集成               │
// │                                                                         │
// │   【调用关系】                                                           │
// │   webSocketMixin.js → this.$socket → socket.js                         │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 什么是Mixin？有什么用？
// A: Vue的代码复用机制，可以将通用逻辑混入多个组件
// 
// Q2: Mixin的合并规则是什么？
// A: data/methods合并（组件优先），生命周期钩子都执行
// 
// Q3: 为什么用Mixin而不是继承？
// A: Vue不支持继承，Mixin更灵活，可以混入多个
// 
// Q4: Mixin有什么缺点？
// A: 命名冲突、来源不明确、调试困难
// 
// Q5: Vue 3中用什么替代Mixin？
// A: Composition API（组合式API）
// 
// Q6: 为什么要在beforeDestroy中清理监听器？
// A: 防止内存泄漏，组件销毁后不再需要监听事件
// ============================================================

// ============================================================
// 导出Mixin对象
// ============================================================
// 【格式】export default { data, methods, 生命周期钩子 }
// 【使用方法】
// import webSocketMixin from '../mixins/webSocketMixin';
// 
// export default {
//   mixins: [webSocketMixin],
//   mounted() {
//     this.initWebSocket();
//     this.addSocketListener('newMessage', this.handleNewMessage);
//   }
// }
// ============================================================
export default {
  
  // ============================================================
  // data: 混入的数据属性
  // ============================================================
  // 【合并规则】
  // 如果组件也有同名属性，组件的优先级更高
  // 
  // 【面试常问】
  // Q: 如果组件也有socketConnected属性会怎样？
  // A: 使用组件的值，Mixin的值被覆盖
  // ============================================================
  data() {
    return {
      // WebSocket连接状态
      // 【类型】boolean
      // 【用途】在模板中显示连接状态，或控制某些功能的可用性
      // 【示例】<div v-if="socketConnected">已连接</div>
      socketConnected: false,
      
      // 事件监听器列表
      // 【类型】Array<{ event: string, handler: Function }>
      // 【数据结构】[{ event: 'newMessage', handler: Function }, ...]
      // 【用途】在组件销毁时批量移除监听器，防止内存泄漏
      // 【添加时机】调用addSocketListener()方法时
      // 【清理时机】组件销毁时（beforeDestroy钩子）
      socketListeners: []
    };
  },
  
  // ============================================================
  // methods: 混入的方法
  // ============================================================
  // 【合并规则】
  // 如果组件也有同名方法，组件的优先级更高
  // 
  // 【面试常问】
  // Q: 如果组件也有initWebSocket方法会怎样？
  // A: 使用组件的方法，Mixin的方法被覆盖
  // ============================================================
  methods: {
    
    // ========================================================
    // 初始化WebSocket连接（核心方法）
    // ========================================================
    // 【作用】建立WebSocket连接并登录
    // 
    // 【调用时机】
    // 在组件的 mounted() 生命周期钩子中调用
    // 
    // 【工作流程】
    // 1. 从 localStorage/sessionStorage 读取用户信息
    // 2. 提取用户ID
    // 3. 调用 socket.js 的 connectAndLogin() 方法
    // 4. 更新连接状态
    // 
    // 【返回值】
    // true: 连接成功
    // false: 连接失败（用户未登录或其他错误）
    // 
    // 【面试常问】
    // Q: 为什么两个存储都读取？
    // A: localStorage记住登录，sessionStorage不记住
    // 
    // Q: $socket 是什么？
    // A: 在main.js中挂载到Vue.prototype的socket实例
    // 
    // Q: 为什么要检查isConnected？
    // A: 避免重复连接，如果已连接则跳过
    // ========================================================
    async initWebSocket() {
      try {
        // ====================================================
        // 步骤1：从本地存储读取用户信息
        // ====================================================
        // 【localStorage vs sessionStorage】
        // localStorage: 记住登录（关闭浏览器后仍然存在）
        // sessionStorage: 不记住登录（关闭浏览器后清除）
        // 
        // 【为什么两个都读？】
        // 用户可能选择"记住我"（localStorage）
        // 也可能没选择（sessionStorage）
        const userStr = localStorage.getItem('user') || sessionStorage.getItem('user');
        
        // 如果没有用户信息，说明未登录
        if (!userStr) {
          console.warn('[WebSocketMixin] 用户未登录，跳过初始化');
          return false;
        }
        
        // 解析用户信息
        // 【JSON.parse】将JSON字符串转为对象
        const user = JSON.parse(userStr);
        
        // ====================================================
        // 步骤2：提取用户ID
        // ====================================================
        // 兼容不同的字段名
        // 有些地方用 _id，有些地方用 id
        const currentUserId = user._id || user.id;
        
        if (!currentUserId) {
          console.warn('[WebSocketMixin] 无法获取用户ID');
          return false;
        }
        
        // ====================================================
        // 步骤3：检查是否已经连接
        // ====================================================
        // 【$socket 是什么？】
        // 在 main.js 中，我们把 socket.js 挂载到 Vue.prototype.$socket
        // 这样所有组件都可以通过 this.$socket 访问
        // 
        // 【挂载代码】
        // Vue.prototype.$socket = socket;
        if (!this.$socket.isConnected) {
          // 连接并登录
          // 【connectAndLogin】一步完成连接和登录
          await this.$socket.connectAndLogin(currentUserId);
        }
        
        // ====================================================
        // 步骤4：更新连接状态
        // ====================================================
        this.socketConnected = this.$socket.isConnected;
        return this.socketConnected;
        
      } catch (error) {
        console.error('[WebSocketMixin] 初始化失败:', error);
        return false;
      }
    },
    
    // ========================================================
    // 添加WebSocket事件监听器
    // ========================================================
    // 【作用】监听WebSocket事件，并自动记录
    // 
    // 【参数说明】
    // event: 事件名称（如 'newMessage', 'notification'）
    // handler: 事件处理函数
    // 
    // 【为什么要用这个方法而不是直接用 $socket.on？】
    // 1. 自动记录监听器，方便后续清理
    // 2. 防止组件销毁时忘记移除监听器
    // 3. 统一管理所有监听器
    // 
    // 【调用示例】
    // this.addSocketListener('newMessage', (message) => {
    //   this.messages.push(message);
    // });
    // 
    // 【面试常问】
    // Q: 为什么要记录监听器？
    // A: 组件销毁时需要移除，防止内存泄漏
    // 
    // Q: 可以直接用 $socket.on 吗？
    // A: 可以，但需要手动管理清理
    // ========================================================
    addSocketListener(event, handler) {
      if (this.$socket) {
        // 调用底层 socket.js 的 on 方法
        this.$socket.on(event, handler);
        
        // 记录监听器，用于后续清理
        // 【数据结构】{ event: '事件名', handler: 回调函数 }
        this.socketListeners.push({ event, handler });
      }
    },
    
    // ========================================================
    // 移除所有WebSocket事件监听器
    // ========================================================
    // 【作用】批量移除所有已注册的监听器
    // 
    // 【调用时机】
    // 1. 组件销毁时（beforeDestroy 钩子自动调用）
    // 2. 需要重新初始化WebSocket时
    // 
    // 【为什么要移除？】
    // 1. 防止内存泄漏：监听器不会被自动回收
    // 2. 防止组件销毁后仍然收到事件
    // 3. 避免重复处理事件
    // 
    // 【面试常问】
    // Q: 不移除会怎样？
    // A: 内存泄漏，组件销毁后仍可能执行回调
    // 
    // Q: 为什么不用 removeAllListeners？
    // A: 可能移除其他组件添加的监听器，不安全
    // ========================================================
    removeSocketListeners() {
      if (this.$socket && this.socketListeners.length > 0) {
        // 遍历所有监听器，逐个移除
        this.socketListeners.forEach(({ event, handler }) => {
          // 调用底层 socket.js 的 off 方法
          // 传入具体的handler，只移除这个回调
          this.$socket.off(event, handler);
        });
        
        // 清空监听器列表
        this.socketListeners = [];
      }
    },
    
    // ========================================================
    // 断开WebSocket连接
    // ========================================================
    // 【作用】主动断开WebSocket连接
    // 
    // 【调用时机】
    // 用户退出登录时
    // 
    // 【流程】
    // 1. 移除所有监听器
    // 2. 断开连接
    // 3. 更新状态
    // 
    // 【注意】
    // 正常情况下不需要手动调用
    // 浏览器关闭时会自动断开
    // 
    // 【面试常问】
    // Q: 什么时候需要主动断开？
    // A: 用户退出登录、切换账号时
    // ========================================================
    disconnectSocket() {
      if (this.$socket && this.socketConnected) {
        // 先移除所有监听器
        this.removeSocketListeners();
        
        // 断开连接
        this.$socket.disconnect();
        
        // 更新状态
        this.socketConnected = false;
      }
    }
  },
  
  // ============================================================
  // 生命周期钩子
  // ============================================================
  // 【合并规则】
  // Mixin的生命周期钩子会与组件的生命周期钩子合并
  // 两者都会执行，先执行Mixin的，再执行组件的
  // 
  // 【执行顺序】
  // 1. Mixin的beforeCreate
  // 2. 组件的beforeCreate
  // 3. Mixin的created
  // 4. 组件的created
  // 5. Mixin的beforeMount
  // 6. 组件的beforeMount
  // 7. Mixin的mounted
  // 8. 组件的mounted
  // ... 以此类推
  // 
  // 【面试常问】
  // Q: Mixin和组件都有mounted，执行顺序是什么？
  // A: 先执行Mixin的，再执行组件的
  // ============================================================
  
  // ========================================================
  // beforeDestroy 钩子
  // ========================================================
  // 【触发时机】组件销毁之前
  // 【作用】清理资源，防止内存泄漏
  // 
  // 【为什么要在这里清理？】
  // 1. 组件即将销毁，不再需要监听事件
  // 2. 防止组件销毁后仍然收到事件
  // 3. 防止内存泄漏
  // 
  // 【面试常问】
  // Q: 为什么不在destroyed中清理？
  // A: destroyed时组件已销毁，可能无法正确访问this
  // 
  // Q: Vue 3中用什么替代beforeDestroy？
  // A: beforeUnmount
  // ========================================================
  beforeDestroy() {
    // 组件销毁前，自动清理所有监听器
    // 【重要】这是防止内存泄漏的关键！
    this.removeSocketListeners();
  }
};
