  │                                                                         │
  │  【面试题】Q: 什么时候不能用箭头函数？                                    │
  │  A: 1. 对象方法中（this 会指向外层而不是对象）                          │
  │     2. 构造函数中（不能 new）                                           │
  │     3. 需要 arguments 时                                                │
  │     4. Vue 的生命周期和 methods 中（需要组件实例的 this）               │
