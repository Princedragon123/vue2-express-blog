// ============================================================
// socket.js - WebSocket客户端服务（学习版·前端核心）
// ============================================================
// 
// 【文件职责】
// 这是WebSocket系统的前端核心，负责：
// 1. 连接后端WebSocket服务器
// 2. 发送事件给后端
// 3. 监听后端推送的事件
// 4. 自动重连机制
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 单例模式：整个应用共享一个WebSocket连接                             │
// │  2. 事件驱动：on监听事件，emit发送事件                                   │
// │  3. 自动重连：断线后自动尝试重新连接                                     │
// │  4. Promise封装：连接操作返回Promise，支持async/await                   │
// │  5. 状态管理：isConnected、reconnectAttempts等状态                      │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【前后端通信流程图】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   前端 socket.js                         后端 socketService.js         │
// │   ─────────────                          ─────────────────────         │
// │                                                                         │
// │   1. 连接阶段                                                           │
// │   ┌─────────────────┐                   ┌─────────────────┐           │
// │   │ io(url)         │ ──────────────→  │ io.on('connection')│         │
// │   │ (创建连接)       │                   │ (监听连接)        │           │
// │   └─────────────────┘                   └─────────────────┘           │
// │                                                                         │
// │   2. 登录阶段                                                           │
// │   ┌─────────────────┐                   ┌─────────────────┐           │
// │   │ emit('login',   │ ──────────────→  │ socket.on('login')│          │
// │   │   userId)       │                   │ (建立映射)        │           │
// │   └─────────────────┘                   └─────────────────┘           │
// │                                                                         │
// │   3. 消息阶段                                                           │
// │   ┌─────────────────┐                   ┌─────────────────┐           │
// │   │ on('newMessage')│ ←──────────────  │ io.to(userId)    │           │
// │   │ (监听消息)       │   .emit('newMessage')               │           │
// │   └─────────────────┘                   └─────────────────┘           │
// │                                                                         │
// │   4. 通知阶段                                                           │
// │   ┌─────────────────┐                   ┌─────────────────┐           │
// │   │ on('notification')│ ←─────────────  │ io.to(userId)    │           │
// │   │ (监听通知)       │   .emit('notification')            │           │
// │   └─────────────────┘                   └─────────────────┘           │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么用单例模式？
// A: 整个应用只需要一个WebSocket连接，避免重复连接浪费资源
// 
// Q2: 如何实现单例模式？
// A: 类定义后立即创建实例并导出：export default new SocketService()
// 
// Q3: 为什么用Promise封装connect？
// A: 支持async/await语法，方便在Vue组件中使用
// 
// Q4: 断线后如何处理？
// A: socket.io自动重连，重连成功后重新发送login事件
// 
// Q5: 为什么重连后要重新登录？
// A: 重连后是新socket，服务器不知道这个连接是谁的
// 
// Q6: 如何防止内存泄漏？
// A: 组件销毁时调用off()移除事件监听器
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================
// 【socket.io-client】WebSocket客户端库
// 提供自动重连、事件监听等功能
import io from 'socket.io-client';

// ============================================================
// SocketService 类
// ============================================================
// 【设计模式】单例模式
// 
// 【什么是单例模式？】
// 确保一个类只有一个实例，并提供全局访问点
// 
// 【为什么WebSocket需要单例？】
// 1. 避免重复连接：每个组件都创建连接会浪费资源
// 2. 统一管理：所有组件共享同一个连接和状态
// 3. 简化代码：不需要在组件间传递socket实例
// 
// 【实现方式】
// class SocketService { ... }
// export default new SocketService(); // 立即创建实例
// 
// 【面试常问】
// Q: 单例模式有什么缺点？
// A: 全局状态难以测试，可能导致意外的副作用
// ============================================================
class SocketService {
  // ============================================================
  // 构造函数
  // ============================================================
  // 【作用】初始化实例属性
  // 【注意】构造函数只执行一次（因为是单例）
  // ============================================================
  constructor() {
    // socket实例（连接成功后赋值）
    // 【类型】Socket.io客户端实例
    // 【初始值】null
    this.socket = null;
    
    // 连接状态
    // 【类型】boolean
    // 【用途】判断是否可以发送消息
    this.isConnected = false;
    
    // ========================================================
    // 重连相关配置
    // ========================================================
    // 当前重连次数
    this.reconnectAttempts = 0;
    
    // 最大重连次数
    // 【作用】防止无限重连
    this.maxReconnectAttempts = 5;
    
    // 重连间隔（毫秒）
    // 【作用】每次重连之间的等待时间
    this.reconnectDelay = 1000;
    
    // 当前登录的用户ID
    // 【作用】重连后自动重新登录
    // 【存储时机】调用login()方法时
    this.currentUserId = null;
  }
  
  // ============================================================
  // 连接WebSocket服务器（核心方法）
  // ============================================================
  // 【作用】建立WebSocket连接
  // 
  // 【参数说明】
  // url: WebSocket服务器地址
  // 默认值：'http://localhost:3001'
  // 
  // 【返回值】
  // Promise - 连接成功resolve，失败reject
  // 
  // 【调用时机】
  // 用户登录后，在webSocketMixin.js的initWebSocket()中调用
  // 
  // 【流程】
  // 1. 创建socket.io实例
  // 2. 监听connect事件
  // 3. 监听connect_error事件
  // 4. 监听disconnect事件
  // 5. 监听reconnect事件
  // 
  // 【面试常问】
  // Q: 为什么用Promise封装？
  // A: 支持async/await，方便在Vue组件中使用
  // 
  // Q: reconnection: true是什么意思？
  // A: 启用socket.io的自动重连功能
  // ============================================================
  connect(url = 'http://localhost:3001') {
    return new Promise((resolve, reject) => {
      try {
        // ========================================================
        // 创建socket连接
        // ========================================================
        // io(url, options)
        // url: 服务器地址
        // options: 配置选项
        this.socket = io(url, {
          // 是否自动重连
          // 【重要】启用后，断线会自动尝试重连
          reconnection: true,
          
          // 最大重连次数
          reconnectionAttempts: this.maxReconnectAttempts,
          
          // 重连间隔（毫秒）
          reconnectionDelay: this.reconnectDelay,
          
          // 连接超时时间（毫秒）
          // 【作用】连接超过20秒未成功则超时
          timeout: 20000
        });
        
        // ========================================================
        // 监听连接成功事件
        // ========================================================
        // 【触发时机】WebSocket连接建立成功
        // 【处理】
        // 1. 更新连接状态
        // 2. 重置重连次数
        // 3. resolve Promise
        // ========================================================
        this.socket.on('connect', () => {
          this.isConnected = true;
          this.reconnectAttempts = 0;
          resolve(); // Promise成功
        });
        
        // ========================================================
        // 监听连接错误事件
        // ========================================================
        // 【触发时机】连接失败
        // 【处理】
        // 1. 更新连接状态
        // 2. reject Promise
        // ========================================================
        this.socket.on('connect_error', (error) => {
          console.error('[Socket] 连接错误:', error);
          this.isConnected = false;
          reject(error); // Promise失败
        });
        
        // ========================================================
        // 监听断开连接事件
        // ========================================================
        // 【触发时机】
        // 1. 网络断开
        // 2. 服务器关闭
        // 3. 用户主动断开
        // 
        // 【参数】reason: 断开原因
        // - 'io server disconnect': 服务器主动断开
        // - 'io client disconnect': 客户端主动断开
        // - 'ping timeout': 心跳超时
        // - 'transport close': 连接关闭
        // - 'transport error': 连接错误
        // ========================================================
        this.socket.on('disconnect', (reason) => {
          this.isConnected = false;
        });
        
        // ========================================================
        // 监听重连成功事件
        // ========================================================
        // 【触发时机】断线后自动重连成功
        // 【重要】重连后必须重新登录！
        // 【原因】重连后是新socket，服务器不知道这个连接是谁的
        // ========================================================
        this.socket.on('reconnect', () => {
          this.isConnected = true;
          this.reconnectAttempts = 0;
          
          // 重连后自动重新登录
          if (this.currentUserId) {
            this.socket.emit('login', this.currentUserId);
          }
        });
        
        // ========================================================
        // 监听重连尝试事件
        // ========================================================
        // 【触发时机】每次尝试重连时
        // 【参数】attemptNumber: 当前尝试次数
        // ========================================================
        this.socket.on('reconnect_attempt', (attemptNumber) => {
          this.reconnectAttempts = attemptNumber;
        });
        
        // ========================================================
        // 监听重连失败事件
        // ========================================================
        // 【触发时机】达到最大重连次数仍失败
        // 【处理】可以提示用户检查网络
        // ========================================================
        this.socket.on('reconnect_failed', () => {
          console.error('[Socket] 重连失败，已达到最大重连次数');
          this.isConnected = false;
        });
        
      } catch (error) {
        console.error('[Socket] 连接初始化失败:', error);
        reject(error);
      }
    });
  }
  
  // ============================================================
  // 断开WebSocket连接
  // ============================================================
  // 【作用】主动断开连接
  // 
  // 【调用时机】
  // 用户退出登录时
  // 
  // 【注意】
  // 正常情况下不需要手动调用
  // 浏览器关闭时会自动断开
  // 
  // 【面试常问】
  // Q: 什么时候需要主动断开？
  // A: 用户退出登录、切换账号时
  // ============================================================
  disconnect() {
    if (this.socket) {
      console.log('[Socket] 主动断开连接');
      this.socket.disconnect();
      this.socket = null;
      this.isConnected = false;
      this.currentUserId = null;
    }
  }
  
  // ============================================================
  // 用户登录
  // ============================================================
  // 【作用】告诉服务器"我是谁"
  // 
  // 【参数说明】
  // userId: 当前登录用户的ID
  // 
  // 【流程】
  // 1. 保存userId（用于重连后重新登录）
  // 2. 发送login事件给服务器
  // 
  // 【服务器处理】
  // 1. 建立userId → socket的映射
  // 2. 将用户加入以userId命名的房间
  // 
  // 【面试常问】
  // Q: 为什么需要login事件？
  // A: socket.io不知道连接的是谁，需要前端主动告知
  // 
  // Q: 为什么保存currentUserId？
  // A: 重连后需要重新登录，需要知道用户ID
  // ============================================================
  login(userId) {
    if (this.socket && this.isConnected) {
      // 保存用户ID（用于重连后重新登录）
      this.currentUserId = userId;
      
      // 发送登录事件
      this.socket.emit('login', userId);
    } else {
      console.warn('[Socket] 未连接，无法登录');
    }
  }
  
  // ============================================================
  // 连接并登录（合并方法）
  // ============================================================
  // 【作用】一步完成连接和登录
  // 
  // 【参数说明】
  // userId: 用户ID
  // url: 服务器地址
  // 
  // 【调用时机】
  // 在webSocketMixin.js中调用
  // 
  // 【调用示例】
  // await socketService.connectAndLogin('user123');
  // ============================================================
  connectAndLogin(userId, url = 'http://localhost:3001') {
    return this.connect(url).then(() => {
      this.login(userId);
    });
  }
  
  // ============================================================
  // 监听WebSocket事件
  // ============================================================
  // 【作用】监听后端推送的事件
  // 
  // 【参数说明】
  // event: 事件名称
  // callback: 回调函数
  // 
  // 【常用事件】
  // - 'newMessage': 收到新私聊消息
  // - 'notification': 收到系统通知
  // - 'messageSent': 消息发送成功确认
  // 
  // 【调用示例】
  // socketService.on('newMessage', (message) => {
  //   console.log('收到新消息:', message);
  //   this.messages.push(message);
  // });
  // 
  // 【面试常问】
  // Q: on和emit有什么区别？
  // A: on是监听事件（接收），emit是发送事件（发出）
  // 
  // Q: 一个事件可以有多个监听器吗？
  // A: 可以，多次调用on注册不同的回调
  // ============================================================
  on(event, callback) {
    if (this.socket) {
      this.socket.on(event, callback);
      console.log(`[Socket] 监听事件: ${event}`);
    } else {
      console.warn('[Socket] 未连接，无法监听事件');
    }
  }
  
  // ============================================================
  // 发送WebSocket事件
  // ============================================================
  // 【作用】向后端发送事件
  // 
  // 【参数说明】
  // event: 事件名称
  // data: 事件数据
  // 
  // 【调用示例】
  // socketService.emit('sendMessage', {
  //   receiver: 'user456',
  //   content: '你好！'
  // });
  // 
  // 【注意】
  // 当前项目中，消息发送是通过HTTP API
  // WebSocket主要用于接收消息和通知
  // ============================================================
  emit(event, data) {
    if (this.socket && this.isConnected) {
      this.socket.emit(event, data);
    } else {
      console.warn('[Socket] 未连接，无法发送事件');
    }
  }
  
  // ============================================================
  // 移除WebSocket事件监听
  // ============================================================
  // 【作用】移除事件监听器
  // 
  // 【参数说明】
  // event: 事件名称
  // callback: 回调函数（可选）
  // 
  // 【为什么需要移除？】
  // 1. 防止内存泄漏
  // 2. 防止组件销毁后仍然收到事件
  // 3. 避免重复处理事件
  // 
  // 【面试常问】
  // Q: 不传callback会怎样？
  // A: 移除该事件的所有监听器
  // 
  // Q: 什么时候需要移除监听器？
  // A: 组件销毁时（beforeDestroy钩子）
  // ============================================================
  off(event, callback) {
    if (this.socket) {
      if (callback) {
        // 移除特定回调
        this.socket.off(event, callback);
      } else {
        // 移除该事件的所有监听器
        this.socket.off(event);
      }
    }
  }
  
  // ============================================================
  // 检查WebSocket连接状态
  // ============================================================
  // 【返回值】
  // true: 已连接
  // false: 未连接
  // 
  // 【用途】
  // 在发送消息前检查连接状态
  // ============================================================
  getConnectionStatus() {
    return this.isConnected;
  }
  
  // ============================================================
  // 获取Socket实例
  // ============================================================
  // 【作用】获取底层socket.io实例
  // 
  // 【注意】
  // 一般情况下不需要使用
  // 只有需要直接操作socket.io时才使用
  // ============================================================
  getSocket() {
    return this.socket;
  }
}

