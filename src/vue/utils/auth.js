// ============================================================
// auth.js - 全局认证状态管理模块（学习版·Vue响应式状态）
// ============================================================
// 
// 【文件职责】
// 管理用户认证状态，包括：
// 1. 用户信息存储
// 2. Token 管理
// 3. 登录/登出处理
// 4. 认证状态检查
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. Vue.observable：创建响应式对象                                      │
// │  2. localStorage vs sessionStorage：持久化 vs 会话级存储                │
// │  3. JWT Token：JSON Web Token 认证机制                                  │
// │  4. 单例模式：全局唯一的认证状态管理                                    │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【Vue.observable 基础】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【什么是响应式？】                                                      │
// │  当数据变化时，视图自动更新                                              │
// │                                                                         │
// │  【Vue.observable 的作用】                                               │
// │  让普通对象变成响应式对象                                                │
// │  在 Vue 2.6+ 中引入，用于小型状态管理                                   │
// │                                                                         │
// │  【示例】                                                                │
// │  const state = Vue.observable({ count: 0 });                           │
// │  // 当 state.count 变化时，使用它的组件会自动重新渲染                   │
// │                                                                         │
// │  【与 Vuex 的区别】                                                      │
// │  - Vuex：大型应用，完整的状态管理模式                                   │
// │  - Vue.observable：小型应用，轻量级状态管理                             │
// │                                                                         │
// │  【面试常问】                                                            │
// │  Q: 为什么不用普通对象？                                                │
// │  A: 普通对象变化时，视图不会自动更新                                    │
// │                                                                         │
// │  Q: Vue.set 的作用？                                                    │
// │  A: 确保新添加的属性也是响应式的                                        │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【localStorage vs sessionStorage】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  特性          │ localStorage          │ sessionStorage               │
// │  ─────────────┼───────────────────────┼─────────────────────────────  │
// │  生命周期      │ 永久（除非手动清除）   │ 会话结束（关闭浏览器）        │
// │  存储大小      │ 约5MB                 │ 约5MB                        │
// │  适用场景      │ 记住登录              │ 临时会话                     │
// │  跨标签页      │ 是                    │ 否（同一标签页共享）          │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【JWT Token 认证流程】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   用户登录                                                              │
// │   ────────                                                             │
// │       │                                                                 │
// │       ▼                                                                 │
// │   服务器验证用户名密码                                                  │
// │   ───────────────────                                                   │
// │       │                                                                 │
// │       ▼                                                                 │
// │   服务器生成 JWT Token                                                  │
// │   ───────────────────                                                   │
// │       │                                                                 │
// │       │  Token 结构：Header.Payload.Signature                          │
// │       │  - Header: 算法信息                                             │
// │       │  - Payload: 用户信息（不敏感）                                  │
// │       │  - Signature: 签名（防篡改）                                    │
// │       ▼                                                                 │
// │   客户端存储 Token                                                      │
// │   ────────────────                                                      │
// │       │                                                                 │
// │       │  存储位置：localStorage 或 sessionStorage                       │
// │       ▼                                                                 │
// │   后续请求携带 Token                                                    │
// │   ───────────────────                                                   │
// │       │                                                                 │
// │       │  请求头：Authorization: Bearer <token>                         │
// │       ▼                                                                 │
// │   服务器验证 Token                                                      │
// │   ────────────────                                                      │
// │       │                                                                 │
// │       ├── 有效 → 返回数据                                               │
// │       │                                                                 │
// │       └── 无效/过期 → 返回 401                                          │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: JWT Token 存在哪里好？
// A: localStorage（方便但XSS风险）或 httpOnly cookie（安全但CSRF风险）
// 
// Q2: Token 过期怎么处理？
// A: 401时刷新token或重新登录
// 
// Q3: 如何防止XSS攻击窃取Token？
// A: 使用 httpOnly cookie，或设置较短的过期时间
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================
// Vue: 用于创建响应式状态
import Vue from 'vue';

// ============================================================
// 认证状态管理对象
// ============================================================
// 【设计模式】单例模式
// 整个应用只有一个 auth 实例，确保状态一致
// 
// 【模块结构】
// - state: 响应式状态
// - init(): 初始化方法
// - loginSuccess(): 登录成功处理
// - logout(): 登出处理
// - 其他辅助方法...
// ============================================================
const auth = {
  // ========================================================
  // 响应式状态
  // ========================================================
  // 【Vue.observable】让对象变成响应式
  // 当这些属性变化时，使用它们的组件会自动重新渲染
  // 
  // 【状态说明】
  // - user: 当前登录用户信息
  // - token: JWT认证令牌
  // - isAuthenticated: 是否已认证
  // - isLoading: 是否正在加载
  // - error: 错误信息
  // ========================================================
  state: Vue.observable({
    // 当前用户信息
    // 【结构】{ _id, username, email, profile: { avatar, bio }, role, ... }
    user: null,
    
    // JWT令牌
    // 【格式】Bearer token 字符串
    // 【用途】每次请求都需要携带，用于身份验证
    token: null,
    
    // 认证状态
    // 【用途】快速判断用户是否已登录
    // 【使用】v-if="auth.state.isAuthenticated"
    isAuthenticated: false,
    
    // 加载状态
    // 【用途】显示加载动画，防止重复提交
    isLoading: false,
    
    // 错误信息
    // 【用途】显示登录/注册错误
    error: null
  }),
  
  // ========================================================
  // 初始化认证状态
  // ========================================================
  // 【调用时机】
  // 1. 应用启动时（main.js 中导入）
  // 2. 页面刷新时
  // 
  // 【作用】
  // 从浏览器存储中恢复登录状态
  // 这样用户刷新页面后不需要重新登录
  // ========================================================
  init() {
    // ----------------------------------------------------
    // 步骤1：从存储中获取token和用户信息
    // ----------------------------------------------------
    // localStorage: 持久化存储，关闭浏览器后仍然存在
    // sessionStorage: 会话级存储，关闭浏览器后清除
    const localToken = localStorage.getItem('token');
    const sessionToken = sessionStorage.getItem('token');
    const localUser = localStorage.getItem('user');
    const sessionUser = sessionStorage.getItem('user');
    
    // ----------------------------------------------------
    // 步骤2：确定使用哪个存储的数据
    // ----------------------------------------------------
    // 优先使用 localStorage（用户选择了"记住我"）
    // 其次使用 sessionStorage（用户没有选择"记住我"）
    this.state.token = localToken || sessionToken;
    const userStr = localUser || sessionUser;
    
    // 解析用户信息
    // JSON.parse: 将JSON字符串转为对象
    this.state.user = userStr ? JSON.parse(userStr) : null;
    
    // ----------------------------------------------------
    // 步骤3：设置认证状态
    // ----------------------------------------------------
    if (this.state.token && this.state.user) {
      // 有token和用户信息，标记为已登录
      this.state.isAuthenticated = true;
    } else {
      // 没有token或用户信息，标记为未登录
      this.state.isAuthenticated = false;
    }
  },
  
  // ========================================================
  // 检查token是否有效
  // ========================================================
  // 【用途】验证token是否存在且未过期
  // 【返回】true: 有效, false: 无效
  // 
  // 【扩展】可以添加JWT解析和过期时间检查
  // ========================================================
  checkTokenValidity() {
    // 检查token是否存在
    if (!this.state.token) {
      // token不存在，执行登出
      this.logout();
      return false;
    }
    
    // 【扩展】可以解析JWT检查过期时间
    // try {
    //   const payload = JSON.parse(atob(this.state.token.split('.')[1]));
    //   if (payload.exp * 1000 < Date.now()) {
    //     // token已过期
    //     this.logout();
    //     return false;
    //   }
    // } catch (e) {
    //   // token格式错误
    //   this.logout();
    //   return false;
    // }
    
    return true;
  },
  
  // ========================================================
  // 检查登录状态并在过期时跳转到登录页
  // ========================================================
  // 【参数】router - Vue Router 实例
  // 【用途】路由守卫中使用，保护需要登录的页面
  // 
  // 【使用示例】
  // router.beforeEach((to, from, next) => {
  //   if (to.meta.requiresAuth) {
  //     if (!auth.checkAuthAndRedirect(router)) {
  //       return; // 未登录，已跳转到登录页
  //     }
  //   }
  //   next();
  // });
  // ========================================================
  checkAuthAndRedirect(router) {
    // 检查认证状态和token有效性
    if (!this.state.isAuthenticated || !this.checkTokenValidity()) {
      if (router && router.currentRoute) {
        const currentPath = router.currentRoute.path;
        
        // 排除登录、注册页面
        // 避免在这些页面时跳转造成循环
        if (currentPath !== '/login' && 
            currentPath !== '/register') {
          router.push('/login');
        }
      }
      return false;
    }
    return true;
  },
  
  // ========================================================
  // 登录成功处理
  // ========================================================
  // 【参数】
  // - user: 用户信息对象
  // - token: JWT令牌
  // - rememberMe: 是否记住登录（使用localStorage）
  // 
  // 【调用时机】登录/注册成功后
  // ========================================================
  loginSuccess(user, token, rememberMe) {
    // ----------------------------------------------------
    // 步骤1：更新响应式状态
    // ----------------------------------------------------
    // 【Vue.set】确保新属性也是响应式的
    // 等同于 this.state.user = user（Vue 2.6+ 会自动处理）
    Vue.set(this.state, 'user', user);
    Vue.set(this.state, 'token', token);
    Vue.set(this.state, 'isAuthenticated', true);
    Vue.set(this.state, 'error', null);
    
    // ----------------------------------------------------
    // 步骤2：持久化存储
    // ----------------------------------------------------
    // 根据rememberMe选择存储方式
    // - true: localStorage（关闭浏览器后仍然保留）
    // - false: sessionStorage（关闭浏览器后清除）
    const storage = rememberMe ? localStorage : sessionStorage;
    
    // 存储token
    storage.setItem('token', token);
    
    // 存储用户信息
    // JSON.stringify: 将对象转为JSON字符串
    // 因为localStorage/sessionStorage只能存储字符串
    storage.setItem('user', JSON.stringify(user));
  },
  
  // ========================================================
  // 登出处理
  // ========================================================
  // 【用途】清除所有认证信息
  // 【调用时机】
  // 1. 用户主动登出
  // 2. Token过期
  // 3. 服务器返回401
  // ========================================================
  logout() {
    // ----------------------------------------------------
    // 步骤1：清除响应式状态
    // ----------------------------------------------------
    Vue.set(this.state, 'user', null);
    Vue.set(this.state, 'token', null);
    Vue.set(this.state, 'isAuthenticated', false);
    Vue.set(this.state, 'error', null);
    
    // ----------------------------------------------------
    // 步骤2：清除浏览器存储
    // ----------------------------------------------------
    // 同时清除localStorage和sessionStorage
    // 因为不确定用户之前选择的是哪种存储方式
    localStorage.removeItem('token');
    sessionStorage.removeItem('token');
    localStorage.removeItem('user');
    sessionStorage.removeItem('user');
  },
  
  // ========================================================
  // 辅助方法：设置/清除错误
  // ========================================================
  setError(error) {
    this.state.error = error;
  },
  
  clearError() {
    this.state.error = null;
  },
  
  // ========================================================
  // 辅助方法：设置加载状态
  // ========================================================
  setLoading(loading) {
    this.state.isLoading = loading;
  },
  
  // ========================================================
  // 辅助方法：获取当前用户信息
  // ========================================================
  // 【返回】用户对象或null
  // 【使用】
  // const user = auth.getCurrentUser();
  // if (user) {
  //   console.log('当前用户:', user.username);
  // }
  // ========================================================
  getCurrentUser() {
    return this.state.user;
  },
  
  // ========================================================
  // 辅助方法：获取token
  // ========================================================
  // 【返回】token字符串或null
  // 【使用】在API拦截器中添加到请求头
  // const token = auth.getToken();
  // config.headers.Authorization = `Bearer ${token}`;
  // ========================================================
  getToken() {
    return this.state.token;
  },
  
  // ========================================================
  // 辅助方法：检查是否已登录
  // ========================================================
  // 【返回】boolean
  // 【使用】
  // if (auth.isLoggedIn()) {
  //   // 已登录，显示用户信息
  // } else {
  //   // 未登录，显示登录按钮
  // }
  // ========================================================
  isLoggedIn() {
    return this.state.isAuthenticated;
  },
  
  // ========================================================
  // 辅助方法：检查是否正在加载
  // ========================================================
  isLoading() {
    return this.state.isLoading;
  },
  
  // ========================================================
  // 辅助方法：获取错误信息
  // ========================================================
  getError() {
    return this.state.error;
  }
};

// ============================================================
// 初始化认证状态
// ============================================================
// 【重要】在导出前调用，确保状态正确初始化
// 这样其他模块导入时，状态已经初始化完成
// ============================================================
auth.init();

