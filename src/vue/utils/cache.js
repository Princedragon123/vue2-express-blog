// A: 防止数据过时，保证数据新鲜度
// 
// Q2: LocalStorage 有什么限制？
// A: 只能存字符串，需要 JSON 序列化；容量有限；同步操作可能阻塞
// 
// Q3: 如何处理 LocalStorage 满了的情况？
// A: try-catch 捕获异常，清除旧缓存或提示用户
