// 【文件职责】
// 提供前端数据缓存功能，包括：
// 1. 设置缓存（带过期时间）
// 2. 获取缓存（自动检查过期）
// 3. 删除缓存
// 4. 清除所有/过期缓存
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. LocalStorage：浏览器本地存储                                        │
// │  2. 缓存过期机制：时间戳 + 过期时间                                      │
// │  3. 命名空间：使用前缀避免冲突                                          │
// │  4. 静态方法：不需要实例化，直接调用                                    │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【缓存数据结构】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  localStorage 中的存储格式：                                             │
// │  ┌─────────────────────────────────────────────────────────────┐       │
// │  │  Key: "blog_cache_user_123"                                  │       │
// │  │  Value: {                                                    │       │
// │  │    "value": { name: "张三", age: 25 },                      │       │
// │  │    "expiry": 1704067200000  // 过期时间戳                    │       │
// │  │  }                                                           │       │
// │  └─────────────────────────────────────────────────────────────┘       │
// │                                                                         │
// │  【字段说明】                                                            │
// │  - value: 实际缓存的数据                                                │
// │  - expiry: 过期时间（毫秒时间戳）                                       │
// │                                                                         │
// │  【过期判断】                                                            │
// │  if (Date.now() > item.expiry) {                                       │
// │    // 已过期，删除缓存                                                  │
// │  }                                                                      │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【使用场景】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【场景1：缓存用户信息】                                                  │
// │  CacheManager.set('user_123', userData, 3600);  // 缓存1小时           │
// │  const user = CacheManager.get('user_123');                            │
// │                                                                         │
// │  【场景2：缓存博客列表】                                                  │
// │  CacheManager.set('blogs_page_1', blogs, 300);  // 缓存5分钟           │
// │  const blogs = CacheManager.get('blogs_page_1');                       │
// │                                                                         │
// │  【场景3：缓存搜索结果】                                                  │
// │  CacheManager.set('search_' + keyword, results, 600);                  │
// │                                                                         │
// │  【场景4：退出登录时清除缓存】                                            │
// │  CacheManager.clear();  // 清除所有缓存                                 │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【LocalStorage vs SessionStorage vs Cookie】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【LocalStorage】                                                        │
// │  - 持久化存储，除非手动清除                                              │
// │  - 容量约 5MB                                                          │
// │  - 同源共享                                                            │
// │  - 适合：用户设置、主题偏好等持久数据                                    │
// │                                                                         │
// │  【SessionStorage】                                                      │
// │  - 会话级存储，关闭标签页即清除                                          │
// │  - 容量约 5MB                                                          │
// │  - 仅当前标签页可用                                                    │
// │  - 适合：临时表单数据、会话状态                                          │
// │                                                                         │
// │  【Cookie】                                                              │
// │  - 可设置过期时间                                                       │
// │  - 容量约 4KB                                                          │
// │  - 每次请求自动发送到服务器                                             │
// │  - 适合：认证 Token、用户 ID                                            │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
