// ============================================================
// server.js - 服务器入口文件（学习版·Express + Socket.io）
// ============================================================
// 
// 【文件职责】
// 创建和配置 Express 服务器，包括：
// 1. 加载中间件
// 2. 配置路由
// 3. 初始化 WebSocket
// 4. 连接数据库
// 5. 启动服务器
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. Express 应用创建和配置                                               │
// │  2. 中间件加载顺序：安全 → 解析 → 路由                                  │
// │  3. WebSocket 初始化：Socket.io 与 HTTP 服务器共享端口                  │
// │  4. 静态文件服务：express.static                                        │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【服务器启动流程】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   1. 加载环境变量                                                       │
// │   ────────────────                                                      │
// │       require('dotenv').config()                                       │
// │       从 .env 文件加载配置                                              │
// │       │                                                                 │
// │       ▼                                                                 │
// │   2. 创建 Express 应用                                                  │
// │   ──────────────────                                                    │
// │       const app = express()                                            │
// │       │                                                                 │
// │       ▼                                                                 │
// │   3. 配置中间件（按顺序）                                               │
// │   ──────────────────                                                    │
// │       ├── helmet()      // HTTP 安全头                                 │
// │       ├── xss()         // XSS 防护                                    │
// │       ├── express.json() // JSON 解析                                  │
// │       ├── express.urlencoded() // URL 编码解析                         │
// │       ├── cors()        // 跨域配置                                    │
// │       │                                                                 │
// │       ▼                                                                 │
// │   4. 配置路由                                                           │
// │   ────────────                                                          │
// │       app.use('/api', routes)                                          │
// │       │                                                                 │
// │       ▼                                                                 │
// │   5. 配置静态文件                                                       │
// │   ────────────────                                                      │
// │       app.use('/static/uploads', express.static('src/uploads'))        │
// │       │                                                                 │
// │       ▼                                                                 │
// │   6. 创建 HTTP 服务器                                                   │
// │   ──────────────────                                                    │
// │       const server = http.createServer(app)                            │
// │       │                                                                 │
// │       ▼                                                                 │
// │   7. 初始化 WebSocket                                                   │
// │   ──────────────────                                                    │
// │       socketService.init(server)                                       │
// │       │                                                                 │
// │       ▼                                                                 │
// │   8. 启动服务器监听                                                     │
// │   ────────────────                                                      │
// │       server.listen(PORT, callback)                                    │
// │       │                                                                 │
// │       ▼                                                                 │
// │   9. 连接数据库                                                         │
// │   ────────────                                                          │
// │       connectDB()                                                       │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【中间件执行顺序】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   请求 → helmet → xss → json解析 → urlencoded → cors → 路由 → 响应     │
// │                                                                         │
// │   【为什么这个顺序？】                                                    │
// │   1. helmet: 最先添加安全头，保护后续处理                                │
// │   2. xss: 尽早过滤恶意输入                                              │
// │   3. json/urlencoded: 解析请求体，路由需要用到                          │
// │   4. cors: 处理跨域，在路由之前                                         │
// │   5. 路由: 最后处理业务逻辑                                             │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【HTTP vs WebSocket 共享端口】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   【传统方式】                                                           │
// │   HTTP Server: 3001 端口                                               │
// │   WebSocket Server: 3002 端口                                          │
// │   需要两个端口，配置复杂                                                │
// │                                                                         │
// │   【共享端口方式】                                                        │
// │   const server = http.createServer(app);  // HTTP 服务器               │
// │   socketService.init(server);             // WebSocket 共享服务器       │
// │   server.listen(3001);                    // 只需一个端口               │
// │                                                                         │
// │   【原理】                                                               │
// │   Socket.io 会监听 HTTP 服务器的 upgrade 事件                          │
// │   当收到 WebSocket 升级请求时，接管连接                                  │
// │   普通 HTTP 请求仍由 Express 处理                                       │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么用 http.createServer 而不是直接 app.listen？
// A: 因为 WebSocket 需要共享 HTTP 服务器
// 
// Q2: helmet 和 xss-clean 有什么区别？
// A: helmet 设置安全响应头，xss-clean 过滤请求体中的恶意代码
// 
// Q3: 为什么数据库连接放在最后？
// A: 非阻塞模式，即使数据库连接失败，服务器也能启动
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================

// Express 框架
const express = require('express');

// HTTP 模块（Node.js 内置）
// 【用途】创建 HTTP 服务器，供 Express 和 Socket.io 共享
const http = require('http');

// 路径处理模块
const path = require('path');

// 环境变量配置
// 【用途】从 .env 文件加载环境变量到 process.env
require('dotenv').config();

// 数据库连接模块
const connectDB = require('./config/database');

// 主路由
const routes = require('./routes');

// CORS 跨域中间件
const cors = require('cors');

// 安全中间件
const helmet = require('helmet');
const xss = require('xss-clean');

// WebSocket 服务
const socketService = require('./services/socketService');

// ============================================================
// 创建 Express 应用
// ============================================================
const app = express();

// ============================================================
// 配置中间件（顺序很重要！）
// ============================================================

// ========================================================
// 1. 安全中间件
// ========================================================

// helmet - 设置 HTTP 安全头
// 【作用】
// - X-Content-Type-Options: 防止 MIME 类型嗅探
// - X-Frame-Options: 防止点击劫持
// - X-XSS-Protection: XSS 过滤器
// - 等等...
app.use(helmet());

// xss-clean - 过滤 XSS 攻击
// 【作用】清理请求体中的恶意 HTML/JS 代码
app.use(xss());

// ========================================================
// 2. 请求体解析中间件
// ========================================================

// 解析 JSON 请求体
// 【作用】req.body 可以访问 JSON 数据
// 【示例】Content-Type: application/json
app.use(express.json());

// 解析 URL-encoded 请求体
// 【作用】解析表单提交的数据
// 【extended: true】使用 qs 库解析，支持嵌套对象
app.use(express.urlencoded({ extended: true }));

// ========================================================
// 3. CORS 跨域配置
// ========================================================
// 【origin】允许的源
// 【credentials】允许携带 Cookie
app.use(cors({
    origin: function(origin, callback) {
        // 允许没有 origin 的请求（如 Postman、移动端）
        if (!origin) return callback(null, true);
        
        // 允许所有 localhost 端口
        if (origin.indexOf('http://localhost:') === 0 || 
            origin.indexOf('http://127.0.0.1:') === 0) {
            return callback(null, true);
        }
        
        // 其他请求拒绝
        callback(new Error('Not allowed by CORS'));
    },
    credentials: true
}));

// ========================================================
// 4. 路由配置
// ========================================================
// 【前缀】所有 API 路由都以 /api 开头
// 【示例】
// /api/auth/login
// /api/blogs
// /api/messages
app.use('/api', routes);

// ============================================================
// 配置静态文件服务
// ============================================================
// 【用途】让浏览器可以访问上传的文件
// 【映射】
// URL: /static/uploads/avatars/xxx.jpg
// 文件：src/uploads/avatars/xxx.jpg
// ============================================================
app.use('/static/uploads', express.static('src/uploads'));
app.use('/static', express.static('src/public'));
app.use('/static/images', express.static('static/images'));

// 测试静态文件访问
app.get('/test-static', (req, res) => {
    res.send('静态文件服务测试');
});

// ============================================================
// 首页路由
// ============================================================
app.get('/', (req, res) => {
    res.send('API服务器正在运行，请通过前端应用访问：http://localhost:8081');
});

// 测试路由
app.get('/api/test', (req, res) => {
    res.json({ success: true, message: 'API测试成功' });
});

// ============================================================
// 创建 HTTP 服务器
// ============================================================
// 【重要】使用 http.createServer 而不是 app.listen
// 【原因】WebSocket 需要共享同一个 HTTP 服务器
const server = http.createServer(app);

// ============================================================
// 初始化 WebSocket 服务
// ============================================================
// 【参数】HTTP 服务器实例
// 【效果】Socket.io 会监听该服务器的连接
socketService.init(server);

// ============================================================
// 启动服务器
// ============================================================
// 【PORT】从环境变量读取，默认 3001
const PORT = process.env.PORT || 3001;

server.listen(PORT, () => {
    console.log(`服务器已启动，监听端口 ${PORT}`);
    console.log(`WebSocket 服务已启动，使用端口 ${PORT}`);
});

// ============================================================
// 连接数据库（非阻塞模式）
// ============================================================
// 【非阻塞】即使数据库连接失败，服务器仍能运行
// 【好处】前端可以使用模拟数据进行开发测试
connectDB().catch(error => {
    console.error('数据库连接失败，服务器将使用模拟数据:', error.message);
    console.log('服务器已启动，前端可以使用模拟数据');
});

// ============================================================
// 导出 app 和 server（用于测试）
// ============================================================
module.exports = { app, server };
