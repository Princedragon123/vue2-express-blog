// ============================================================
// BrowseHistory.js - 浏览历史模型
// ============================================================
// 
// 【文件职责】
// 定义浏览历史（BrowseHistory）的数据结构，记录用户浏览过的文章
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 浏览记录设计：用户 + 文章 + 时间戳                                  │
// │  2. 复合唯一索引：防止重复记录                                          │
// │  3. 时间戳字段：记录最后浏览时间                                        │
// │  4. 历史记录排序：按时间倒序                                            │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【浏览历史数据模型】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【BrowseHistory 浏览历史表】                                            │
// │  ├── _id: 记录ID                                                        │
// │  ├── user: 用户ID → 关联 User 表                                       │
// │  ├── blog: 文章ID → 关联 Blog 表                                       │
// │  └── timestamp: 最后浏览时间                                            │
// │                                                                         │
// │  【设计要点】                                                            │
// │  1. 用户重复浏览同一文章时，更新时间戳而非创建新记录                   │
// │  2. 按时间倒序排列，最近浏览的在最前面                                 │
// │  3. 可以设置过期时间，自动清理旧记录                                   │
// │                                                                         │
// │  【与收藏的区别】                                                        │
// │  ├── 浏览历史：自动记录，被动行为                                      │
// │  └── 收藏：用户主动操作，主动行为                                      │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【浏览历史查询示例】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  // 获取用户最近浏览的20篇文章                                         │
// │  BrowseHistory.find({ user: userId })                                   │
// │    .populate('blog', 'title image excerpt')                            │
// │    .sort({ timestamp: -1 })  // 按时间倒序                             │
// │    .limit(20)                                                          │
// │                                                                         │
// │  // 清空用户浏览历史                                                    │
// │  BrowseHistory.deleteMany({ user: userId })                            │
// │                                                                         │
// │  // 删除单条浏览记录                                                    │
// │  BrowseHistory.findOneAndDelete({ _id: id, user: userId })             │
// │                                                                         │
// │  // 更新浏览时间（用户再次浏览）                                        │
// │  BrowseHistory.findOneAndUpdate(                                        │
// │    { user: userId, blog: blogId },                                     │
// │    { timestamp: Date.now() },                                          │
// │    { upsert: true, new: true }                                         │
// │  )                                                                      │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【upsert 操作说明】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  upsert = update + insert                                               │
// │                                                                         │
// │  【工作流程】                                                            │
// │  1. 查找匹配的文档                                                      │
// │  2. 找到 → 更新该文档                                                  │
// │  3. 找不到 → 创建新文档                                                │
// │                                                                         │
// │  【浏览历史场景】                                                        │
// │  用户第一次浏览文章A → 创建新记录                                      │
// │  用户再次浏览文章A → 更新时间戳                                        │
// │                                                                         │
// │  【代码示例】                                                            │
// │  BrowseHistory.findOneAndUpdate(                                        │
// │    { user: userId, blog: blogId },  // 查询条件                         │
// │    { timestamp: Date.now() },       // 更新内容                         │
// │    { upsert: true, new: true }      // 选项                             │
// │  )                                                                      │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// ============================================================

// ============================================================
// 【模块导入】
// ============================================================

const mongoose = require('mongoose');

// ============================================================
// 【浏览历史模式定义】
// ============================================================

const browseHistorySchema = new mongoose.Schema({
    
    // --------------------------------------------------------
    // 【用户字段】浏览者
    // --------------------------------------------------------
    user: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    
    // --------------------------------------------------------
    // 【文章字段】被浏览的文章
    // --------------------------------------------------------
    blog: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Blog',
        required: true
    },
    
    // --------------------------------------------------------
    // 【时间戳】最后浏览时间
    // --------------------------------------------------------
    // 注意：这里用 timestamp 而非 createdAt
    // 因为用户可能多次浏览同一文章，需要更新时间
    // --------------------------------------------------------
    timestamp: {
        type: Date,
        default: Date.now
    }
});

// ============================================================
// 【复合唯一索引】
// ============================================================
// 确保每个用户对每篇文章只有一条浏览记录
// 当用户再次浏览时，更新 timestamp 而非创建新记录
// ============================================================
browseHistorySchema.index({ user: 1, blog: 1 }, { unique: true });

// ============================================================
// 【创建浏览历史模型】
// ============================================================
// 'BrowseHistory' → 'browsehistories' 集合
// ============================================================
const BrowseHistory = mongoose.models.BrowseHistory || mongoose.model('BrowseHistory', browseHistorySchema);

// ============================================================
// 【模块导出】
// ============================================================
module.exports = BrowseHistory;
