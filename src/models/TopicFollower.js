// ============================================================
// TopicFollower.js - 话题关注模型
// ============================================================
// 
// 【文件职责】
// 记录用户与话题的关注关系，用于：
// 1. 判断用户是否关注某话题
// 2. 获取用户关注的话题列表
// 3. 获取话题的关注者列表
// 4. 统计话题关注数
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 关联模型：用户与话题的多对多关系                                    │
// │  2. 复合唯一索引：防止重复关注                                          │
// │  3. 时间戳：记录关注时间                                                │
// │  4. 双向查询：用户→话题、话题→用户                                     │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【话题关注流程】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   用户点击关注                                                          │
// │   ────────────                                                          │
// │       │                                                                 │
// │       │ POST /api/topics/:id/follow                                    │
// │       ▼                                                                 │
// │   检查是否已关注                                                        │
// │   ────────────                                                          │
// │       │                                                                 │
// │       │ TopicFollower.findOne({ userId, topicId })                     │
// │       │                                                                 │
// │       ├── 已关注 → 取消关注                                            │
// │       │   TopicFollower.deleteOne({ userId, topicId })                 │
// │       │   Topic.followersCount--                                       │
// │       │                                                                 │
// │       └── 未关注 → 添加关注                                            │
// │           TopicFollower.create({ userId, topicId })                    │
// │           Topic.followersCount++                                       │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【多对多关系图解】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【用户表】              【话题关注表】              【话题表】          │
// │  ┌─────────┐            ┌─────────────┐            ┌─────────┐         │
// │  │ User    │            │TopicFollower│            │ Topic   │         │
// │  ├─────────┤            ├─────────────┤            ├─────────┤         │
// │  │ _id     │←───────────│ userId      │            │ _id     │         │
// │  │ username│            │ topicId     │───────────→│ name    │         │
// │  │ ...     │            │ followedAt  │            │ ...     │         │
// │  └─────────┘            └─────────────┘            └─────────┘         │
// │                                                                         │
// │  【示例数据】                                                            │
// │  用户A 关注 话题1 → { userId: A, topicId: 1 }                          │
// │  用户A 关注 话题2 → { userId: A, topicId: 2 }                          │
// │  用户B 关注 话题1 → { userId: B, topicId: 1 }                          │
// │                                                                         │
// │  【查询示例】                                                            │
// │  - 用户A 关注了哪些话题？                                               │
// │    TopicFollower.find({ userId: A }).populate('topicId')               │
// │                                                                         │
// │  - 话题1 有哪些关注者？                                                 │
// │    TopicFollower.find({ topicId: 1 }).populate('userId')               │
// │                                                                         │
// │  - 用户A 是否关注话题1？                                                │
// │    TopicFollower.findOne({ userId: A, topicId: 1 })                    │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么需要单独的关注表？
// A: 用户和话题是多对多关系，需要中间表存储关联
// 
// Q2: 如何保证不重复关注？
// A: 复合唯一索引 { userId: 1, topicId: 1 }
// 
// Q3: 关注/取消关注如何更新计数？
// A: 使用 $inc 操作符原子性更新
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================

// Mongoose：MongoDB 对象建模工具
const mongoose = require('mongoose');

// ============================================================
// 定义话题关注模式
// ============================================================
const topicFollowerSchema = new mongoose.Schema({
    // ========================================================
    // 用户 ID
    // ========================================================
    // 【类型】ObjectId
    // 【关联】User 模型
    // 【必填】true
    // 【用途】
    // - 查询用户关注的话题
    // - 判断用户是否关注某话题
    userId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    
    // ========================================================
    // 话题 ID
    // ========================================================
    // 【类型】ObjectId
    // 【关联】Topic 模型
    // 【必填】true
    // 【用途】
    // - 查询话题的关注者
    // - 统计话题关注数
    topicId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Topic',
        required: true
    },
    
    // ========================================================
    // 关注时间
    // ========================================================
    // 【类型】Date
    // 【默认】当前时间
    // 【用途】
    // - 按关注时间排序
    // - 分析用户关注趋势
    followedAt: {
        type: Date,
        default: Date.now
    }
});

// ============================================================
// 创建索引
// ============================================================

// 复合唯一索引
// 【作用】确保用户不会重复关注同一个话题
// 【字段】userId + topicId
// 【unique: true】唯一约束
topicFollowerSchema.index({ userId: 1, topicId: 1 }, { unique: true });

// 用户关注时间索引
// 【用途】查询用户关注的话题，按时间倒序
topicFollowerSchema.index({ userId: 1, followedAt: -1 });

// 话题关注时间索引
// 【用途】查询话题的关注者，按时间倒序
topicFollowerSchema.index({ topicId: 1, followedAt: -1 });

// ============================================================
// 创建话题关注模型
// ============================================================
const TopicFollower = mongoose.model('TopicFollower', topicFollowerSchema);

