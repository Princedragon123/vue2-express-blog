// ============================================================
// Like.js - 点赞模型
// ============================================================
// 
// 【文件职责】
// 定义点赞（Like）的数据结构，支持对博客和评论的点赞
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 多态关联：一个模型关联多种内容类型                                  │
// │  2. enum 枚举：限制字段取值范围                                         │
// │  3. 三字段复合索引：更复杂的唯一约束                                    │
// │  4. 内容类型区分：contentType 字段                                      │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【点赞系统数据模型】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【Like 点赞表】                                                         │
// │  ├── _id: 点赞记录ID                                                    │
// │  ├── user: 用户ID → 关联 User 表                                       │
// │  ├── contentId: 内容ID → 关联 Blog 或 Comment 表                       │
// │  ├── contentType: 内容类型（'blog' 或 'comment'）                      │
// │  └── createdAt: 点赞时间                                                │
// │                                                                         │
// │  【多态关联说明】                                                        │
// │  ├── contentType = 'blog' → contentId 关联 Blog 表                    │
// │  └── contentType = 'comment' → contentId 关联 Comment 表              │
// │                                                                         │
// │  【唯一约束】                                                            │
// │  (user, contentId, contentType) 组合必须唯一                           │
// │  即：用户对同一类型的内容只能点赞一次                                   │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【多态关联详解】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【传统方式 vs 多态方式】                                                │
// │                                                                         │
// │  传统方式（两个表）：                                                    │
// │  ├── BlogLike 表（user, blog）                                         │
// │  └── CommentLike 表（user, comment）                                   │
// │                                                                         │
// │  多态方式（一个表）：                                                    │
// │  └── Like 表（user, contentId, contentType）                           │
// │                                                                         │
// │  【多态方式优点】                                                        │
// │  1. 统一的点赞查询接口                                                  │
// │  2. 扩展新的内容类型只需添加 enum 值                                   │
// │  3. 统一的点赞统计                                                      │
// │                                                                         │
// │  【查询示例】                                                            │
// │  // 查询用户的所有点赞                                                  │
// │  Like.find({ user: userId })                                           │
// │                                                                         │
// │  // 查询博客的所有点赞                                                  │
// │  Like.find({ contentId: blogId, contentType: 'blog' })                 │
// │                                                                         │
// │  // 查询评论的所有点赞                                                  │
// │  Like.find({ contentId: commentId, contentType: 'comment' })           │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【enum 枚举验证】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  contentType: {                                                         │
// │    type: String,                                                        │
// │    enum: ['blog', 'comment'],  // 只能是这两个值                        │
// │    required: true                                                       │
// │  }                                                                      │
// │                                                                         │
// │  【验证效果】                                                            │
// │  ├── 'blog' → 通过                                                     │
// │  ├── 'comment' → 通过                                                  │
// │  └── 'article' → 报错（不在枚举值中）                                  │
// │                                                                         │
// │  【错误信息】                                                            │
// │  ValidationError: `article` is not a valid enum value for path `contentType`.│
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// ============================================================

// ============================================================
// 【模块导入】
// ============================================================

const mongoose = require('mongoose');

// ============================================================
// 【点赞模式定义】
// ============================================================

const likeSchema = new mongoose.Schema({
    
    // --------------------------------------------------------
    // 【用户字段】点赞的用户
    // --------------------------------------------------------
    user: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    
    // --------------------------------------------------------
    // 【内容ID】被点赞的内容
    // --------------------------------------------------------
    // 不指定 ref，因为可能是 Blog 或 Comment
    // 需要根据 contentType 来确定关联哪个模型
    // --------------------------------------------------------
    contentId: {
        type: mongoose.Schema.Types.ObjectId,
        required: true
    },
    
    // --------------------------------------------------------
    // 【内容类型】区分点赞的是博客还是评论
    // --------------------------------------------------------
    // enum - 枚举验证，限制只能取指定的值
    // 'blog' - 博客点赞
    // 'comment' - 评论点赞
    // --------------------------------------------------------
    contentType: {
        type: String,
        enum: ['blog', 'comment'],
        required: true
    },
    
    // --------------------------------------------------------
    // 【创建时间】点赞时间
    // --------------------------------------------------------
    createdAt: {
        type: Date,
        default: Date.now
    }
});

// ============================================================
// 【三字段复合唯一索引】
// ============================================================
// 确保用户对同一类型的内容只能点赞一次
// 索引键：(user, contentId, contentType)
// ============================================================
likeSchema.index({ user: 1, contentId: 1, contentType: 1 }, { unique: true });

// ============================================================
// 【创建点赞模型】
// ============================================================
// 'Like' → 'likes' 集合
// ============================================================
const Like = mongoose.models.Like || mongoose.model('Like', likeSchema);

// ============================================================
// 【模块导出】
// ============================================================
module.exports = Like;
