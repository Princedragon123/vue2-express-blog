// ============================================================
// 导入依赖模块
// ============================================================

// Mongoose：MongoDB 对象建模工具
const mongoose = require('mongoose');

// ============================================================
// 定义搜索记录模式
// ============================================================
const searchRecordSchema = new mongoose.Schema({
  // ========================================================
  // 搜索关键词
  // ========================================================
  // 【类型】String
  // 【必填】true
  // 【处理】trim 去除首尾空格
  // 【用途】
  // - 热门搜索统计
  // - 搜索推荐
  // - 关键词分析
  keyword: {
    type: String,
    required: true,
    trim: true
  },
  
  // ========================================================
  // 搜索用户
  // ========================================================
  // 【类型】ObjectId
  // 【关联】User 模型
  // 【默认】null（未登录用户也可以搜索）
  // 
  // 【设计考虑】
  // - 未登录用户：user = null，通过 IP 追踪
  // - 已登录用户：user = userId，可关联用户画像
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    default: null
  },
  
  // ========================================================
  // 搜索时间
  // ========================================================
  // 【类型】Date
  // 【默认】当前时间
  // 【用途】
  // - 时间范围统计（今日热门、本周热门）
  // - 搜索趋势分析
  createdAt: {
    type: Date,
    default: Date.now
  },
  
  // ========================================================
  // 搜索结果数量
  // ========================================================
  // 【类型】Number
  // 【默认】0
  // 【用途】
  // - 分析搜索效果
  // - 优化搜索算法（无结果的关键词需要优化）
  resultCount: {
    type: Number,
    default: 0
  },
  
  // ========================================================
  // 搜索 IP
  // ========================================================
  // 【类型】String
  // 【默认】空字符串
  // 【用途】
  // - 追踪未登录用户
  // - 防刷统计
  // - 地域分析
  // 
  // 【隐私考虑】
  // - 可以对 IP 进行脱敏处理
  // - 定期清理 IP 数据
  ip: {
    type: String,
    default: ''
  }
});

// ============================================================
// 创建索引
// ============================================================

// 关键词索引
// 【用途】快速按关键词查询和统计
searchRecordSchema.index({ keyword: 1 });

// 时间索引
// 【用途】按时间范围查询（-1 表示降序）
// 【场景】获取最近7天的热门搜索
searchRecordSchema.index({ createdAt: -1 });

