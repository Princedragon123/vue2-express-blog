// ============================================================
// Notification.js - 用户通知模型
// ============================================================
// 
// 【文件职责】
// 定义用户通知数据结构，包括：
// 1. 通知类型（点赞、评论、关注等）
// 2. 发送者和接收者信息
// 3. 关联资源信息
// 4. 已读状态
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 通知类型枚举：like, comment, reply, collect, follow, mention       │
// │  2. 双向引用：receiver 和 sender 都引用 User 模型                       │
// │  3. 资源关联：resourceId + resourceType 实现多态关联                    │
// │  4. 与 WebSocket 的关系：实时推送通知                                   │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【通知系统架构】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   用户A 点赞文章                                                        │
// │   ─────────────                                                        │
// │       │                                                                 │
// │       ▼                                                                 │
// │   BlogController 处理点赞请求                                           │
// │   ───────────────────────────                                          │
// │       │                                                                 │
// │       ├── 1. 更新文章点赞数                                             │
// │       │                                                                 │
// │       ├── 2. 创建 Notification 文档                                     │
// │       │       {                                                         │
// │       │         receiver: 文章作者ID,                                   │
// │       │         sender: 用户A的ID,                                      │
// │       │         type: 'like',                                           │
// │       │         resourceId: 文章ID,                                     │
// │       │         resourceType: 'blog'                                    │
// │       │       }                                                         │
// │       │                                                                 │
// │       ├── 3. 通过 WebSocket 推送通知                                    │
// │       │       socketService.sendNotification(作者ID, {...})             │
// │       │                                                                 │
// │       ▼                                                                 │
// │   用户B（文章作者）收到实时通知                                          │
// │   ───────────────────────────                                          │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【通知类型说明】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  类型      │ 触发场景              │ resourceType │ 示例内容            │
// │  ─────────┼───────────────────────┼──────────────┼───────────────────  │
// │  like      │ 有人点赞你的文章      │ blog         │ "xxx点赞了你的文章" │
// │  comment   │ 有人评论你的文章      │ blog         │ "xxx评论了你的文章" │
// │  reply     │ 有人回复你的评论      │ comment      │ "xxx回复了你的评论" │
// │  collect   │ 有人收藏你的文章      │ blog         │ "xxx收藏了你的文章" │
// │  follow    │ 有人关注你            │ user         │ "xxx关注了你"       │
// │  mention   │ 有人@提及你           │ comment      │ "xxx在评论中提及你" │
// │  message   │ 有人给你发私信        │ message      │ "xxx给你发送了消息" │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【多态关联】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【什么是多态关联？】                                                    │
// │  一个字段可以关联不同类型的模型                                         │
// │                                                                         │
// │  【实现方式】                                                            │
// │  resourceId: 存储关联文档的ID                                           │
// │  resourceType: 存储关联文档的类型                                       │
// │                                                                         │
// │  【示例】                                                                │
// │  // 点赞通知                                                            │
// │  { resourceId: blogId, resourceType: 'blog' }                          │
// │                                                                         │
// │  // 回复通知                                                            │
// │  { resourceId: commentId, resourceType: 'comment' }                    │
// │                                                                         │
// │  【查询时填充】                                                          │
// │  // 根据 resourceType 动态 populate                                    │
// │  if (notification.resourceType === 'blog') {                           │
// │    await Notification.populate(notification, {                         │
// │      path: 'resourceId',                                               │
// │      model: 'Blog'                                                     │
// │    });                                                                  │
// │  }                                                                      │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 如何实现未读消息数量统计？
// A: Notification.countDocuments({ receiver: userId, isRead: false })
// 
// Q2: 如何批量标记已读？
// A: Notification.updateMany({ receiver: userId }, { isRead: true })
// 
// Q3: 通知数据会无限增长吗？
// A: 需要定期清理旧通知，或设置过期时间（TTL索引）
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================
const mongoose = require('mongoose');

// ============================================================
// 定义通知 Schema
// ============================================================
const notificationSchema = new mongoose.Schema({
    // ========================================================
    // 接收者（引用 User 模型）
    // ========================================================
    // 【用途】谁会收到这条通知
    // 【示例】点赞时，接收者是文章作者
    // ========================================================
    receiver: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: [true, '接收者不能为空']
    },
    
    // ========================================================
    // 发送者（引用 User 模型）
    // ========================================================
    // 【用途】谁触发了这条通知
    // 【示例】点赞时，发送者是点赞的用户
    // ========================================================
    sender: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: [true, '发送者不能为空']
    },
    
    // ========================================================
    // 通知类型
    // ========================================================
    // 【枚举值说明】
    // - like: 点赞通知
    // - comment: 评论通知
    // - reply: 回复通知
    // - collect: 收藏通知
    // - follow: 关注通知
    // - mention: @提及通知
    // - message: 私信通知
    // 
    // 【面试常问】
    // Q: 为什么用枚举而不是字符串？
    // A: 限制取值范围，防止无效数据，便于查询
    // ========================================================
    type: {
        type: String,
        enum: {
            values: ['like', 'comment', 'reply', 'collect', 'follow', 'mention', 'message'],
            message: '通知类型无效'
        },
        required: [true, '通知类型不能为空']
    },
    
    // ========================================================
    // 通知内容
    // ========================================================
    // 【用途】存储通知的文本描述
    // 【示例】"xxx点赞了你的文章《...》"
    // 【可选】有些通知可能不需要额外内容
    // ========================================================
    content: {
        type: String,
        trim: true
    },
    
    // ========================================================
    // 相关资源ID（多态关联）
    // ========================================================
    // 【用途】存储触发通知的资源ID
    // 【配合 resourceType 使用】
    // 
    // 【示例】
    // - 点赞通知：resourceId = 文章ID, resourceType = 'blog'
    // - 评论通知：resourceId = 评论ID, resourceType = 'comment'
    // - 关注通知：resourceId = 关注者ID, resourceType = 'user'
    // ========================================================
    resourceId: {
        type: mongoose.Schema.Types.ObjectId,
        required: [true, '资源ID不能为空']
    },
    
    // ========================================================
    // 资源类型（多态关联）
    // ========================================================
    // 【用途】标识 resourceId 关联的是哪种类型的文档
    // 【枚举值】blog, comment, user, message
    // 
    // 【面试常问】
    // Q: 为什么需要 resourceType？
    // A: 因为 resourceId 可能关联不同类型的文档，
    //    需要 resourceType 来确定如何 populate
    // ========================================================
    resourceType: {
        type: String,
        enum: {
            values: ['blog', 'comment', 'user', 'message'],
            message: '资源类型无效'
        },
        required: [true, '资源类型不能为空']
    },
    
    // ========================================================
    // 是否已读
    // ========================================================
    // 【用途】标记通知是否被用户查看
    // 【默认值】false（未读）
    // 
    // 【更新时机】
    // - 用户点击通知时
    // - 用户打开通知列表时
    // - 用户点击"全部标记已读"时
    // ========================================================
    isRead: {
        type: Boolean,
        default: false
    },
    
    // 创建时间
    createdAt: {
        type: Date,
        default: Date.now
    }
});

// ============================================================
// 创建索引（可选，提升查询性能）
// ============================================================

// 复合索引：接收者 + 已读状态 + 时间
// 【用途】快速查询用户的未读通知
notificationSchema.index({ receiver: 1, isRead: 1, createdAt: -1 });

// 索引：接收者 + 时间
// 【用途】获取用户的通知列表（包含已读和未读）
notificationSchema.index({ receiver: 1, createdAt: -1 });

// ============================================================
// 创建通知模型
// ============================================================
// 【集合名】notifications（自动转为小写复数）
// ============================================================
const Notification = mongoose.model('Notification', notificationSchema);

