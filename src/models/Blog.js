// ============================================================
// Blog.js - 博客文章模型
// ============================================================
// 
// 【文件职责】
// 定义博客文章数据结构，包括：
// 1. 文章基本信息（标题、内容、摘要）
// 2. 文章类型（长文章/短文章）
// 3. 媒体文件（图片、视频）
// 4. 关联数据（作者、分类、话题）
// 5. 统计数据（点赞、评论、浏览、收藏）
// 6. 状态管理（草稿/已发布）
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. ObjectId 引用：关联其他模型（User, Category, Topic）                │
// │  2. 嵌套数组：mediaFiles, images, tags                                 │
// │  3. 文本索引：提升搜索性能                                              │
// │  4. 枚举值：articleType, status                                        │
// │  5. populate：填充关联数据                                              │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【MongoDB 关联关系】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【ObjectId 引用】                                                       │
// │  MongoDB 是文档数据库，没有外键约束                                     │
// │  通过 ObjectId 引用实现"关联"                                           │
// │                                                                         │
// │  【示例】                                                                │
// │  author: {                                                              │
// │    type: mongoose.Schema.Types.ObjectId,  // ObjectId 类型             │
// │    ref: 'User'                             // 引用 User 模型            │
// │  }                                                                      │
// │                                                                         │
// │  【populate 填充】                                                       │
// │  Blog.findById(id).populate('author')                                   │
// │  // 返回的 author 会从 ObjectId 变成完整的用户对象                       │
// │                                                                         │
// │  【面试常问】                                                            │
// │  Q: MongoDB 如何实现一对多？                                            │
// │  A: 在"多"的一方存储"一"的 ObjectId                                    │
// │                                                                         │
// │  Q: populate 的性能问题？                                               │
// │  A: 每次 populate 都是一次额外查询，大量数据时要谨慎                    │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【文章类型对比】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  类型      │ 特点                        │ 适用场景                     │
// │  ─────────┼─────────────────────────────┼───────────────────────────  │
// │  long      │ 富文本编辑器、封面图、视频   │ 教程、攻略、长文             │
// │  short     │ 短文本、多图/视频           │ 动态、分享、简短内容         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么需要 plainTextContent？
// A: 富文本包含HTML标签，纯文本用于搜索和SEO
// 
// Q2: 文本索引和普通索引的区别？
// A: 文本索引支持全文搜索，普通索引支持精确匹配和排序
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================
const mongoose = require('mongoose');

// ============================================================
// 定义博客 Schema
// ============================================================
const blogSchema = new mongoose.Schema({
    // ========================================================
    // 文章标题
    // ========================================================
    // 【验证规则】
    // minlength: 5 - 最短5个字符
    // maxlength: 100 - 最长100个字符
    // 【SEO建议】标题包含关键词，长度适中
    // ========================================================
    title: {
        type: String,
        required: [true, '标题不能为空'],
        trim: true,
        minlength: [5, '标题至少5个字符'],
        maxlength: [100, '标题最多100个字符']
    },
    
    // ========================================================
    // 文章内容（富文本）
    // ========================================================
    // 【存储格式】HTML字符串
    // 【来源】富文本编辑器（如 Quill, TinyMCE）
    // 【注意】存储前需要做 XSS 过滤
    // ========================================================
    content: {
        type: String
    },
    
    // ========================================================
    // 纯文本内容
    // ========================================================
    // 【用途】
    // 1. 全文搜索（HTML标签会干扰搜索）
    // 2. SEO 描述
    // 3. 生成摘要
    // 
    // 【生成方式】
    // 去除HTML标签，只保留文本内容
    // plainTextContent = content.replace(/<[^>]*>/g, '')
    // ========================================================
    plainTextContent: {
        type: String,
        trim: true
    },
    
    // ========================================================
    // 文章摘要（已删除）
    // ========================================================
    // 【说明】原 excerpt 字段已删除，因无实际使用场景
    // ========================================================
    
    // ========================================================
    // 文章类型
    // ========================================================
    // 【类型说明】
    // - long: 长文章，使用富文本编辑器
    // - short: 短文章，类似微博/朋友圈
    // 
    // 【区别】
    // long: 有 content, image, video
    // short: 有 shortContent, mediaFiles
    // ========================================================
    articleType: {
        type: String,
        enum: {
            values: ['long', 'short'],
            message: '文章类型只能是 long 或 short'
        },
        default: 'long'
    },
    
    // ========================================================
    // 封面图片URL（统一字段）
    // ========================================================

    image: {
        type: String,
        required: [true, '封面图不能为空']
    },
    
    // ========================================================
    // 视频URL（长文章）
    // ========================================================

    video: {
        type: String
    },
    
    // ========================================================
    // 媒体文件列表（短文章）
    // ========================================================
    // 【结构】数组，每个元素包含 url 和 mediaType
    // 【支持】图片和视频混合上传
    // 
    // 【面试常问】
    // Q: 为什么用数组而不是单独字段？
    // A: 短文章可能有多张图片/视频，数量不固定
    // ========================================================
    mediaFiles: [{
        // 媒体文件URL
        url: {
            type: String,
            required: true
        },
        // 媒体类型：图片或视频
        mediaType: {
            type: String,
            enum: {
                values: ['image', 'video'],
                message: '媒体类型只能是 image 或 video'
            },
            default: 'image'
        }
    }],
    
    // ========================================================
    // 短文章内容
    // ========================================================
    shortContent: {
        type: String,
        trim: true,
        maxlength: [2000, '短文章内容最多2000个字符']
    },
    
    // ========================================================
    // 话题标签（类似微博话题）
    // ========================================================
    // 【格式】#话题名称#
    // 【用途】内容分类、话题聚合
    // ========================================================
    hashtags: [{
        type: String,
        trim: true
    }],
    
    // 位置信息
    location: {
        type: String,
        trim: true
    },
    
    // ========================================================
    // 作者（关联 User 模型）
    // ========================================================
    // 【ObjectId 引用】
    // type: mongoose.Schema.Types.ObjectId - MongoDB对象ID
    // ref: 'User' - 引用 User 模型
    // 
    // 【populate 用法】
    // Blog.findById(id).populate('author', 'username avatar')
    // // 只返回作者的 username 和 avatar
    // 
    // 【面试常问】
    // Q: 为什么用 ObjectId 而不是直接存储用户信息？
    // A: 用户信息可能变化，ObjectId 引用保持同步
    // ========================================================
    author: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: [true, '作者不能为空']
    },
    
 
    
    // ========================================================
    // 话题（关联 Topic 模型）
    // ========================================================
    // 【可选字段】文章可以不属于任何话题
    // 【用途】话题聚合、相关推荐
    // ========================================================
    topic: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Topic'
    },
    
    // ========================================================
    // 标签数组
    // ========================================================
    // 【用途】内容标记、搜索优化
    // 【示例】['Vue', 'JavaScript', '前端']
    // ========================================================
    tags: [{
        type: String,
        trim: true
    }],
    
    // ========================================================
    // 统计数据
    // ========================================================
    // 【更新时机】
    // - likes: 用户点赞时 +1，取消点赞时 -1
    // - comments: 发表评论时 +1，删除评论时 -1
    // - views: 每次访问详情页 +1
    // - bookmarks: 用户收藏时 +1，取消收藏时 -1
    // 【面试常问】
    // Q: 为什么不实时统计？
    // A: 实时统计性能差，预计算存储更高效
    // ========================================================
    likes: {
        type: Number,
        default: 0
    },
    comments: {
        type: Number,
        default: 0
    },
    views: {
        type: Number,
        default: 0
    },
    bookmarks: {
        type: Number,
        default: 0
    },  
    // 创建时间
    createdAt: {
        type: Date,
        default: Date.now
    },
    
    // 更新时间
    updatedAt: {
        type: Date,
        default: Date.now
    }
});

// ============================================================
// 创建索引
// ============================================================
// 【索引类型】
// 1. 文本索引（text）：支持全文搜索
// 2. 普通索引（1/-1）：支持排序和筛选
// 
// 【面试常问】
// Q: 为什么要创建索引？
// A: 提升查询性能，没有索引会全表扫描
// 
// Q: 索引越多越好吗？
// A: 不是，索引会占用存储空间，影响写入性能
// 
// Q: 复合索引的顺序重要吗？
// A: 重要，遵循最左前缀原则
// ============================================================

// 文本索引：支持全文搜索
// 【用法】Blog.find({ $text: { $search: '关键词' } })
blogSchema.index({ 
    title: 'text', 
    content: 'text', 
    shortContent: 'text', 
    plainTextContent: 'text', 
    tags: 'text', 
    hashtags: 'text', 
    excerpt: 'text' 
});

// 普通索引：支持筛选和排序
// 【复合索引】topic + createdAt + articleType
// 【查询优化】按话题筛选、按时间排序时使用
blogSchema.index({ topic: 1, createdAt: -1, articleType: 1 });

// ============================================================
// 创建博客模型
// ============================================================
// 【集合名】blogs（自动转为小写复数）
// ============================================================
const Blog = mongoose.model('Blog', blogSchema);

// ============================================================
// 导出博客模型
// ============================================================
module.exports = Blog;
