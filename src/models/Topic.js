// ============================================================
// Topic.js - 话题模型
// ============================================================
// 
// 【文件职责】
// 定义话题（Topic）的数据结构，用于：
// 1. 文章分类和聚合
// 2. 用户关注话题
// 3. 话题下的文章列表
// 4. 热门话题推荐
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 话题系统：类似知乎、微博的话题功能                                  │
// │  2. 文本索引：$text 索引用于全文搜索                                    │
// │  3. 计数字段：followersCount, articlesCount                             │
// │  4. 排序索引：按热度、时间排序                                          │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【话题系统流程】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   创建话题                                                              │
// │   ────────                                                              │
// │       │                                                                 │
// │       │ POST /api/topics                                               │
// │       │ { name: 'Vue.js', description: 'Vue.js 框架相关' }             │
// │       ▼                                                                 │
// │   用户关注话题                                                          │
// │   ────────────                                                          │
// │       │                                                                 │
// │       │ POST /api/topics/:id/follow                                    │
// │       │ followersCount++                                               │
// │       ▼                                                                 │
// │   发布文章关联话题                                                      │
// │   ────────────────                                                      │
// │       │                                                                 │
// │       │ POST /api/blogs                                                │
// │       │ { topics: ['Vue.js'] }                                         │
// │       │ articlesCount++                                                │
// │       ▼                                                                 │
// │   话题页面展示                                                          │
// │   ────────────                                                          │
// │       │                                                                 │
// │       │ GET /api/topics/:id                                            │
// │       │ 返回话题信息 + 文章列表                                        │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【文本索引详解】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【创建文本索引】                                                        │
// │  topicSchema.index({ name: 'text', description: 'text' });              │
// │                                                                         │
// │  【使用文本搜索】                                                        │
// │  Topic.find({ $text: { $search: 'vue' } })                              │
// │                                                                         │
// │  【搜索结果排序（按相关度）】                                             │
// │  Topic.find(                                                             │
// │    { $text: { $search: 'vue' } },                                       │
// │    { score: { $meta: 'textScore' } }                                    │
// │  ).sort({ score: { $meta: 'textScore' } })                              │
// │                                                                         │
// │  【注意事项】                                                            │
// │  - 每个集合只能有一个文本索引                                           │
// │  - 文本索引会占用较多存储空间                                           │
// │  - 适合中量级数据，大量数据建议用 Elasticsearch                          │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 话题和分类有什么区别？
// A: 分类是层级结构，话题是扁平标签；话题可以关注，分类不行
// 
// Q2: 如何实现热门话题？
// A: 按 followersCount 或 articlesCount 降序排序
// 
// Q3: 如何防止重复话题？
// A: name 字段设置 unique: true
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================

// Mongoose：MongoDB 对象建模工具
const mongoose = require('mongoose');

// ============================================================
// 定义话题模式
// ============================================================
const topicSchema = new mongoose.Schema({
    // ========================================================
    // 话题名称
    // ========================================================
    // 【类型】String
    // 【必填】true
    // 【唯一】true（防止重复话题）
    // 【处理】trim 去除首尾空格
    // 【长度】2-50 个字符
    name: {
        type: String,
        required: true,
        unique: true,
        trim: true,
        minlength: 2,
        maxlength: 50
    },
    
    // ========================================================
    // 话题描述
    // ========================================================
    // 【类型】String
    // 【必填】true
    // 【处理】trim 去除首尾空格
    // 【长度】最大 500 个字符
    description: {
        type: String,
        required: true,
        trim: true,
        maxlength: 500
    },
    
    // ========================================================
    // 话题封面图片
    // ========================================================
    // 【类型】String
    // 【可选】话题的封面图片 URL
    coverImage: {
        type: String
    },
    
    // ========================================================
    // 关注人数
    // ========================================================
    // 【类型】Number
    // 【默认】0
    // 【更新】用户关注/取消关注时 +1/-1
    followersCount: {
        type: Number,
        default: 0
    },
    
    // ========================================================
    // 文章数量
    // ========================================================
    // 【类型】Number
    // 【默认】0
    // 【更新】文章关联/取消关联话题时 +1/-1
    articlesCount: {
        type: Number,
        default: 0
    },
    
    // ========================================================
    // 创建时间
    // ========================================================
    createdAt: {
        type: Date,
        default: Date.now
    },
    
    // ========================================================
    // 更新时间
    // ========================================================
    updatedAt: {
        type: Date,
        default: Date.now
    }
});

// ============================================================
// 创建索引
// ============================================================

// 文本索引
// 【用途】全文搜索话题名称和描述
// 【字段】name, description
topicSchema.index({ name: 'text', description: 'text' });

// 排序索引
// 【用途】按热度、时间排序
// 【字段】followersCount, articlesCount, createdAt
// 【-1】降序（从大到小）
topicSchema.index({ followersCount: -1, articlesCount: -1, createdAt: -1 });

// ============================================================
// 创建话题模型
// ============================================================
const Topic = mongoose.models.Topic || mongoose.model('Topic', topicSchema);

