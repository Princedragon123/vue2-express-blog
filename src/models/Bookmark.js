// ============================================================
// Bookmark.js - 收藏模型
// ============================================================
// 
// 【文件职责】
// 定义收藏（Bookmark）的数据结构，用于存储用户收藏的博客文章
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. ObjectId 关联：引用其他模型                                          │
// │  2. 复合唯一索引：防止重复收藏                                           │
// │  3. ref 引用：populate 填充的基础                                       │
// │  4. 时间戳：记录收藏时间                                                 │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【收藏系统数据模型】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【Bookmark 收藏表】                                                     │
// │  ├── _id: 收藏记录ID（MongoDB自动生成）                                 │
// │  ├── user: 用户ID → 关联 User 表                                       │
// │  ├── blog: 博客ID → 关联 Blog 表                                       │
// │  └── createdAt: 收藏时间                                                │
// │                                                                         │
// │  【关系说明】                                                            │
// │  ├── 一个用户可以收藏多篇文章（一对多）                                 │
// │  ├── 一篇文章可以被多个用户收藏（一对多）                               │
// │  └── 用户-文章组合必须唯一（复合唯一索引）                              │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【复合唯一索引详解】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  bookmarkSchema.index({ user: 1, blog: 1 }, { unique: true })          │
// │                                                                         │
// │  【参数说明】                                                            │
// │  - { user: 1, blog: 1 }  - 复合索引字段                                 │
// │    - user: 1  表示按升序索引                                            │
// │    - blog: 1  表示按升序索引                                            │
// │  - { unique: true }      - 唯一约束                                    │
// │                                                                         │
// │  【效果】                                                                │
// │  ├── 用户A收藏文章1 → 成功                                             │
// │  ├── 用户A再次收藏文章1 → 失败（已存在）                               │
// │  └── 用户B收藏文章1 → 成功（不同用户）                                 │
// │                                                                         │
// │  【索引结构】                                                            │
// │  索引键 = (user_id, blog_id)                                           │
// │  数据库会检查这个组合是否已存在                                         │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【populate 填充原理】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  // 查询收藏记录时填充用户和博客信息                                    │
// │  Bookmark.find()                                                        │
// │    .populate('user', 'username profile.avatar')                        │
// │    .populate('blog', 'title image')                                    │
// │                                                                         │
// │  // 执行流程：                                                           │
// │  1. 查询 Bookmark 集合，获取 user 和 blog 字段（ObjectId）             │
// │  2. 根据 ref 配置，知道 user 关联 User 模型                            │
// │  3. 到 User 集合查找对应的文档                                         │
// │  4. 将 user 字段从 ObjectId 替换为完整的用户对象                       │
// │  5. 同理填充 blog 字段                                                  │
// │                                                                         │
// │  // 填充前：                                                             │
// │  { user: ObjectId('507f1...'), blog: ObjectId('507f2...') }            │
// │                                                                         │
// │  // 填充后：                                                             │
// │  {                                                                      │
// │    user: { _id: '...', username: '张三', profile: {...} },             │
// │    blog: { _id: '...', title: '文章标题', image: '...' }               │
// │  }                                                                      │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// ============================================================

// ============================================================
// 【模块导入】
// ============================================================

const mongoose = require('mongoose');

// ============================================================
// 【收藏模式定义】
// ============================================================

const bookmarkSchema = new mongoose.Schema({
    
    // --------------------------------------------------------
    // 【用户字段】关联 User 模型
    // --------------------------------------------------------
    // type: ObjectId - MongoDB 的特殊类型，用于存储文档ID
    // ref: 'User' - 指定关联的模型名称，用于 populate 填充
    // required: true - 必填字段
    // --------------------------------------------------------
    user: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    
    // --------------------------------------------------------
    // 【博客字段】关联 Blog 模型
    // --------------------------------------------------------
    blog: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Blog',
        required: true
    },
    
    // --------------------------------------------------------
    // 【创建时间】自动记录收藏时间
    // --------------------------------------------------------
    // default: Date.now - 插入文档时自动设置为当前时间
    // 注意：不要写成 Date.now()，否则所有记录都是同一时间
    // --------------------------------------------------------
    createdAt: {
        type: Date,
        default: Date.now
    }
});

// ============================================================
// 【复合唯一索引】
// ============================================================
// 确保一个用户只能收藏一篇文章一次
// user: 1 表示升序，blog: 1 表示升序
// unique: true 表示这个组合必须唯一
// ============================================================
bookmarkSchema.index({ user: 1, blog: 1 }, { unique: true });

// ============================================================
// 【创建收藏模型】
// ============================================================
// mongoose.model(模型名称, 模式定义)
// 模型名称首字母大写，MongoDB 会自动转为小写复数形式作为集合名
// 'Bookmark' → 'bookmarks' 集合
// ============================================================
const Bookmark = mongoose.model('Bookmark', bookmarkSchema);

// ============================================================
// 【模块导出】
// ============================================================
module.exports = Bookmark;
