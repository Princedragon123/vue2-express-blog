// ============================================================
// Message.js - 私信消息模型
// ============================================================
// 
// 【文件职责】
// 定义私信消息数据结构，包括：
// 1. 发送者和接收者信息
// 2. 消息内容和类型
// 3. 附件信息（图片、文件）
// 4. 消息状态（已发送、已送达、已读）
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 双向引用：sender 和 receiver 都引用 User 模型                       │
// │  2. 消息类型：text, image, file                                         │
// │  3. 消息状态：sent, delivered, read                                     │
// │  4. 嵌套对象：attachment 存储附件信息                                    │
// │  5. 与 WebSocket 的关系：实时消息推送                                    │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【私信系统数据流】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   用户A 发送消息                                                        │
// │   ─────────────                                                        │
// │       │                                                                 │
// │       ▼                                                                 │
// │   前端 socket.emit('sendMessage', { to, content })                     │
// │       │                                                                 │
// │       ▼                                                                 │
// │   后端 socket.on('sendMessage')                                        │
// │       │                                                                 │
// │       ├── 1. 创建 Message 文档（存入数据库）                            │
// │       │                                                                 │
// │       ├── 2. 检查用户B是否在线                                          │
// │       │       │                                                         │
// │       │       ├── 在线 → io.to(userB).emit('newMessage')               │
// │       │       │                                                         │
// │       │       └── 离线 → 消息已存数据库，下次登录可获取                 │
// │       │                                                                 │
// │       ▼                                                                 │
// │   完成 ✅                                                               │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【消息状态流转】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   sent ──→ delivered ──→ read                                          │
// │     │          │            │                                          │
// │     │          │            └── 用户B打开聊天界面                       │
// │     │          │                                                        │
// │     │          └── 消息送达用户B设备                                    │
// │     │                                                                   │
// │     └── 消息已发送到服务器                                              │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 如何实现消息已读回执？
// A: 用户B打开聊天时，更新 status 为 'read'，记录 readAt 时间
// 
// Q2: 如何获取两个用户之间的聊天记录？
// A: Message.find({ $or: [{sender: A, receiver: B}, {sender: B, receiver: A}] })
// 
// Q3: 离线消息如何处理？
// A: 所有消息都存数据库，用户上线时查询未读消息
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================
const mongoose = require('mongoose');

// ============================================================
// 定义消息 Schema
// ============================================================
const messageSchema = new mongoose.Schema({
    // ========================================================
    // 发送者（引用 User 模型）
    // ========================================================
    // 【ObjectId 引用】
    // 存储发送者的用户ID，通过 populate 填充详细信息
    // 
    // 【populate 示例】
    // Message.find().populate('sender', 'username avatar')
    // // 只返回发送者的 username 和 avatar
    // ========================================================
    sender: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: [true, '发送者不能为空']
    },
    
    // ========================================================
    // 接收者（引用 User 模型）
    // ========================================================
    // 【双向引用】
    // sender 和 receiver 都引用 User 模型
    // 形成用户之间的对话关系
    // ========================================================
    receiver: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: [true, '接收者不能为空']
    },
    
    // ========================================================
    // 消息内容
    // ========================================================
    // 【验证规则】
    // required: true - 必填
    // trim: true - 去除首尾空格
    // 
    // 【安全考虑】
    // 存储前应进行 XSS 过滤，防止注入攻击
    // ========================================================
    content: {
        type: String,
        required: [true, '消息内容不能为空'],
        trim: true
    },
    
    // ========================================================
    // 消息类型
    // ========================================================
    // 【类型说明】
    // - text: 纯文本消息
    // - image: 图片消息
    // - file: 文件消息
    // 
    // 【不同类型的处理】
    // - text: content 存储文本内容
    // - image: content 存储图片描述，attachment.url 存储图片地址
    // - file: content 存储文件说明，attachment 存储文件信息
    // ========================================================
    type: {
        type: String,
        enum: {
            values: ['text', 'image', 'file'],
            message: '消息类型只能是 text、image 或 file'
        },
        default: 'text'
    },
    
    // ========================================================
    // 附件信息（嵌套对象）
    // ========================================================
    // 【用途】存储图片或文件的详细信息
    // 【可选】只有 type 为 image 或 file 时才有值
    // 
    // 【面试常问】
    // Q: 为什么用嵌套对象而不是单独字段？
    // A: 附件信息是一个整体，组织在一起更清晰
    // ========================================================
    attachment: {
        // 文件路径或URL
        url: {
            type: String
        },
        // 原始文件名
        name: {
            type: String
        },
        // 文件大小（字节）
        // 【用途】前端显示文件大小，限制上传大小
        size: {
            type: Number
        },
        // MIME类型
        // 【示例】image/jpeg, application/pdf
        contentType: {
            type: String
        }
    },
    
    // ========================================================
    // 消息状态
    // ========================================================
    // 【状态说明】
    // - sent: 已发送（消息已存入数据库）
    // - delivered: 已送达（消息已推送给接收者）
    // - read: 已读（接收者已查看消息）
    // 
    // 【状态更新时机】
    // - sent: 消息创建时
    // - delivered: WebSocket 推送成功时
    // - read: 接收者打开聊天界面时
    // ========================================================
    status: {
        type: String,
        enum: {
            values: ['sent', 'delivered', 'read'],
            message: '状态只能是 sent、delivered 或 read'
        },
        default: 'sent'
    },
    
    // 创建时间
    createdAt: {
        type: Date,
        default: Date.now
    },
    
    // ========================================================
    // 阅读时间
    // ========================================================
    // 【用途】记录消息被阅读的时间
    // 【更新时机】status 变为 'read' 时同时更新
    // 
    // 【面试常问】
    // Q: 为什么需要 readAt？
    // A: 可以显示"已读于 xx:xx"，提供更好的用户体验
    // ========================================================
    readAt: {
        type: Date
    }
});

// ============================================================
// 创建索引（可选，提升查询性能）
// ============================================================
// 【常用查询】
// 1. 获取两个用户之间的聊天记录
// 2. 获取用户的未读消息
// 3. 获取最近的会话列表
// ============================================================

// 复合索引：发送者 + 接收者 + 时间
// 【用途】快速查询两个用户之间的聊天记录
messageSchema.index({ sender: 1, receiver: 1, createdAt: -1 });

// 索引：接收者 + 状态
// 【用途】快速查询用户的未读消息
messageSchema.index({ receiver: 1, status: 1 });

// ============================================================
// 创建消息模型
// ============================================================
// 【集合名】messages（自动转为小写复数）
// ============================================================
const Message = mongoose.models.Message || mongoose.model('Message', messageSchema);

