// ============================================================
// blogRoutes.js - 博客路由（学习版·Express Router）
// ============================================================
// 
// 【文件职责】
// 定义博客相关的 API 路由，包括：
// 1. 博客 CRUD（增删改查）
// 2. 点赞和收藏
// 3. 评论功能
// 4. 搜索功能
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. RESTful API 设计：资源 + HTTP 方法                                   │
// │  2. 路由参数：:id 动态匹配博客 ID                                       │
// │  3. 认证保护：部分路由需要登录                                           │
// │  4. 路由顺序：特定路径要在参数路径前面                                   │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【路由表】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  方法   │ 路径                    │ 认证  │ 功能                       │
// │  ──────┼─────────────────────────┼───────┼───────────────────────────│
// │  GET    │ /                       │ 否    │ 获取博客列表               │
// │  POST   │ /                       │ 是    │ 创建新文章                 │
// │  GET    │ /hot                    │ 否    │ 获取热门博客               │
// │  GET    │ /latest                 │ 否    │ 获取最新博客               │
// │  GET    │ /recommended            │ 否    │ 获取推荐博客               │
// │  GET    │ /bookmarks              │ 是    │ 获取收藏列表               │
// │  GET    │ /my                     │ 是    │ 获取我的文章               │
// │  GET    │ /search                 │ 否    │ 搜索文章                   │
// │  GET    │ /:id                    │ 否    │ 获取博客详情               │
// │  GET    │ /:blogId/comments       │ 否    │ 获取评论列表               │
// │  POST   │ /:blogId/comments       │ 是    │ 发表评论                   │
// │  POST   │ /:id/like               │ 是    │ 点赞博客                   │
// │  DELETE │ /:id/like               │ 是    │ 取消点赞                   │
// │  POST   │ /:id/bookmark           │ 是    │ 收藏博客                   │
// │  DELETE │ /:id/bookmark           │ 是    │ 取消收藏                   │
// │  PUT    │ /:id                    │ 是    │ 更新文章                   │
// │  DELETE │ /:id                    │ 是    │ 删除文章                   │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【路由顺序的重要性】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【错误示例】                                                            │
// │  router.get('/:id', ...)           // 会匹配 /hot、/latest 等！        │
// │  router.get('/hot', ...)           // 永远不会执行                      │
// │                                                                         │
// │  【正确示例】                                                            │
// │  router.get('/hot', ...)           // 特定路径在前                      │
// │  router.get('/latest', ...)                                             │
// │  router.get('/:id', ...)           // 参数路径在后                      │
// │                                                                         │
// │  【原因】                                                                │
// │  Express 按定义顺序匹配路由                                             │
// │  :id 是动态参数，会匹配任何字符串                                       │
// │  所以特定路径必须放在前面                                               │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【RESTful 设计原则】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【资源】博客（blogs）                                                   │
// │                                                                         │
// │  【操作】                                                                │
// │  GET    /blogs        → 获取列表（读）                                  │
// │  POST   /blogs        → 创建资源（写）                                  │
// │  GET    /blogs/:id    → 获取单个（读）                                  │
// │  PUT    /blogs/:id    → 更新资源（写）                                  │
// │  DELETE /blogs/:id    → 删除资源（写）                                  │
// │                                                                         │
// │  【子资源】评论（comments）                                              │
// │  GET    /blogs/:blogId/comments    → 获取评论列表                      │
// │  POST   /blogs/:blogId/comments    → 发表评论                          │
// │                                                                         │
// │  【动作】点赞、收藏                                                      │
// │  POST   /blogs/:id/like       → 点赞（创建点赞关系）                    │
// │  DELETE /blogs/:id/like       → 取消点赞（删除点赞关系）                │
// │  POST   /blogs/:id/bookmark   → 收藏（创建收藏关系）                    │
// │  DELETE /blogs/:id/bookmark   → 取消收藏（删除收藏关系）                │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么用 POST 点赞而不是 PUT？
// A: 点赞是创建"点赞关系"，不是更新博客资源
// 
// Q2: 如何设计分页？
// A: GET /blogs?page=1&limit=10
// 
// Q3: 如何设计筛选？
// A: GET /blogs?category=tech&sort=latest
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================
const express = require('express');
const router = express.Router();
const BlogController = require('../controllers/BlogController');
const { authMiddleware } = require('../middlewares/auth');

// ============================================================
// 博客列表相关路由（无参数路径）
// ============================================================

// ========================================================
// GET / - 获取博客列表
// ========================================================
// 【查询参数】
// ?page=1&limit=10&category=tech&sort=latest
// 
// 【响应】
// {
//   blogs: [...],
//   total: 100,
//   page: 1,
//   totalPages: 10
// }
// ========================================================
router.get('/', BlogController.getBlogs);

// ========================================================
// POST / - 创建新文章
// ========================================================
// 【需要认证】authMiddleware
// 【请求体】
// {
//   title: "标题",
//   content: "内容",
//   category: "分类",
//   tags: ["标签1", "标签2"]
// }
// ========================================================
router.post('/', authMiddleware, BlogController.createBlog);

// ========================================================
// GET /hot - 获取热门博客
// ========================================================
// 【排序依据】阅读量、点赞数、评论数等
// 【限制数量】通常返回前 10 篇
// ========================================================
router.get('/hot', BlogController.getHotBlogs);

// ========================================================
// GET /recommended - 获取推荐博客
// ========================================================
// 【推荐算法】
// - 基于用户兴趣
// - 基于热度加权
// - 基于协同过滤
// ========================================================
router.get('/recommended', BlogController.getRecommendedBlogs);

// ========================================================
// GET /bookmarks - 获取用户收藏列表
// ========================================================
// 【需要认证】authMiddleware
// 【返回】当前用户收藏的所有博客
// ========================================================
router.get('/bookmarks', authMiddleware, BlogController.getUserBookmarks);

// ========================================================
// GET /my - 获取我的文章列表
// ========================================================
// 【需要认证】authMiddleware
// 【返回】当前用户发表的所有文章
// ========================================================
router.get('/my', authMiddleware, BlogController.getMyBlogs);

// ========================================================
// GET /search - 搜索文章
// ========================================================
// 【查询参数】
// ?q=关键词&page=1&limit=10
// 
// 【搜索范围】
// 标题、内容、标签等
// ========================================================
router.get('/search', BlogController.searchBlogs);

// ============================================================
// 博客详情相关路由（带参数 :id）
// ============================================================

// ========================================================
// GET /:id - 获取博客详情
// ========================================================
// 【参数】id - 博客 ID
// 【响应】博客完整信息 + 作者信息 + 评论数等
// 【注意】放在所有无参数路由之后
// ========================================================
router.get('/:id', BlogController.getBlogDetail);

// ========================================================
// GET /:blogId/comments - 获取博客评论列表
// ========================================================
// 【参数】blogId - 博客 ID
// 【响应】评论列表（嵌套结构）
// ========================================================
router.get('/:blogId/comments', BlogController.getBlogComments);

// ========================================================
// POST /:blogId/comments - 创建评论
// ========================================================
// 【需要认证】authMiddleware
// 【请求体】
// {
//   content: "评论内容",
//   parentId: "父评论ID（可选）",
//   replyTo: "回复用户ID（可选）"
// }
// ========================================================
router.post('/:blogId/comments', authMiddleware, BlogController.createComment);

// ============================================================
// 评论相关路由
// ============================================================

// ========================================================
// DELETE /comments/:commentId - 删除评论
// ========================================================
// 【需要认证】authMiddleware
// 【权限检查】只能删除自己的评论
// ========================================================
router.delete('/comments/:commentId', authMiddleware, BlogController.deleteComment);

// ============================================================
// 点赞相关路由
// ============================================================

// ========================================================
// POST /:id/like - 点赞博客
// ========================================================
// 【需要认证】authMiddleware
// 【实现】
// 1. 检查是否已点赞
// 2. 创建点赞记录
// 3. 更新博客点赞数 +1
// 4. 发送通知给作者（WebSocket）
// ========================================================
router.post('/:id/like', authMiddleware, BlogController.likeBlog);

// ========================================================
// DELETE /:id/like - 取消点赞
// ========================================================
// 【需要认证】authMiddleware
// 【实现】
// 1. 删除点赞记录
// 2. 更新博客点赞数 -1
// ========================================================
router.delete('/:id/like', authMiddleware, BlogController.unlikeBlog);

// ========================================================
// GET /:id/is-liked - 检查是否已点赞
// ========================================================
// 【需要认证】authMiddleware
// 【响应】{ isLiked: true/false }
// ========================================================
router.get('/:id/is-liked', authMiddleware, BlogController.checkLikeStatus);

// ============================================================
// 收藏相关路由
// ============================================================

// ========================================================
// GET /:id/is-bookmarked - 检查是否已收藏
// ========================================================
// 【需要认证】authMiddleware
// 【响应】{ isBookmarked: true/false }
// ========================================================
router.get('/:id/is-bookmarked', authMiddleware, BlogController.checkBookmarkStatus);

// ========================================================
// POST /:id/bookmark - 收藏博客
// ========================================================
// 【需要认证】authMiddleware
// 【实现】
// 1. 检查是否已收藏
// 2. 创建收藏记录
// 3. 更新博客收藏数 +1
// 4. 发送通知给作者（WebSocket）
// ========================================================
router.post('/:id/bookmark', authMiddleware, BlogController.bookmarkBlog);

// ========================================================
// DELETE /:id/bookmark - 取消收藏
// ========================================================
// 【需要认证】authMiddleware
// ========================================================
router.delete('/:id/bookmark', authMiddleware, BlogController.unbookmarkBlog);

// ============================================================
// 博客修改/删除路由
// ============================================================

// ========================================================
// PUT /:id - 更新文章
// ========================================================
// 【需要认证】authMiddleware
// 【权限检查】只能更新自己的文章
// 【请求体】要更新的字段
// ========================================================
router.put('/:id', authMiddleware, BlogController.updateBlog);

// ========================================================
// DELETE /:id - 删除文章
// ========================================================
// 【需要认证】authMiddleware
// 【权限检查】只能删除自己的文章
// 【级联删除】相关评论、点赞、收藏记录
// ========================================================
router.delete('/:id', authMiddleware, BlogController.deleteBlog);

// ========================================================
// POST /upload-image - 上传文章图片
// ========================================================
// 【需要认证】authMiddleware
// 【用途】富文本编辑器上传图片
// 【请求】FormData: image = 文件
// 【返回】{ url: '图片 URL', alt: '文件名', width: 800, height: 600 }
// ========================================================
router.post('/upload-image', authMiddleware, BlogController.uploadBlogImage);

// ========================================================
// POST /upload-video - 上传文章视频
// ========================================================
// 【需要认证】authMiddleware
// 【用途】富文本编辑器上传视频
// 【请求】FormData: video = 文件
// 【返回】{ url: '视频 URL', name: '文件名', size: 大小 }
// ========================================================
router.post('/upload-video', authMiddleware, BlogController.uploadBlogVideo);

// ============================================================
// 导出路由
// ============================================================
// 【挂载方式】在 index.js 中：
// router.use('/blogs', blogRoutes);
// 
// 【最终路径示例】
// GET  /blogs           → 获取列表
// POST /blogs           → 创建文章
// GET  /blogs/hot       → 热门博客
// GET  /blogs/:id       → 博客详情
// POST /blogs/:id/like  → 点赞
// POST /blogs/upload-image → 上传图片
// POST /blogs/upload-video → 上传视频
// ============================================================
module.exports = router;
