// ============================================================
// browseHistoryRoutes.js - 浏览记录路由
// ============================================================
// 
// 【文件职责】
// 定义浏览记录相关的 API 路由，包括：
// 1. 添加浏览记录
// 2. 获取浏览历史
// 3. 删除单条记录
// 4. 清空所有记录
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 用户行为追踪：记录用户浏览过的文章                                  │
// │  2. 路由级中间件：使用 router.use() 统一应用中间件                      │
// │  3. 隐私数据处理：浏览记录属于用户隐私                                  │
// │  4. 数据清理：提供清空功能防止数据膨胀                                  │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【浏览记录系统架构】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   【用户浏览文章流程】                                                   │
// │   ┌─────────────────────────────────────────────────────────────────┐  │
// │   │                                                                 │  │
// │   │   用户点击文章                                                   │  │
// │   │       │                                                         │  │
// │   │       ▼                                                         │  │
// │   │   前端请求文章详情                                               │  │
// │   │       │                                                         │  │
// │   │       ├── GET /api/blogs/:id  获取文章内容                      │  │
// │   │       │                                                         │  │
// │   │       └── POST /api/browse-history  添加浏览记录                │  │
// │   │               │                                                 │  │
// │   │               ▼                                                 │  │
// │   │           保存到数据库                                           │  │
// │   │           BrowseHistory 集合                                    │  │
// │   │               │                                                 │  │
// │   │               ▼                                                 │  │
// │   │           用户下次可查看历史                                     │  │
// │   │                                                                 │  │
// │   └─────────────────────────────────────────────────────────────────┘  │
// │                                                                         │
// │   【BrowseHistory 数据结构】                                             │
// │   ┌─────────────────────────────────────────────────────────────────┐  │
// │   │  user        用户ID                                             │  │
// │   │  blog        文章ID                                             │  │
// │   │  viewedAt    浏览时间                                           │  │
// │   │  duration    停留时长（可选）                                    │  │
// │   └─────────────────────────────────────────────────────────────────┘  │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【路由级中间件】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   【什么是路由级中间件？】                                               │
// │   路由级中间件只对当前路由模块生效                                      │
// │   使用 router.use(middleware) 应用到所有路由                            │
// │                                                                         │
// │   【与全局中间件的区别】                                                 │
// │   ┌─────────────────────────────────────────────────────────────────┐  │
// │   │  全局中间件                                                      │  │
// │   │  app.use(authMiddleware)  // 对所有路由生效                      │  │
// │   │                                                                 │  │
// │   │  路由级中间件                                                    │  │
// │   │  router.use(authMiddleware)  // 只对当前路由模块生效             │  │
// │   └─────────────────────────────────────────────────────────────────┘  │
// │                                                                         │
// │   【为什么浏览记录路由全部需要认证？】                                   │
// │   浏览记录是用户的私密数据，只有用户本人可以查看和管理                  │
// │   所以所有操作都需要验证身份                                            │
// │                                                                         │
// │   【代码示例】                                                           │
// │   router.use(authMiddleware)  // 统一应用到下面所有路由                │
// │   router.get('/', getHistory)      // 自动需要认证                    │
// │   router.delete('/', clearHistory) // 自动需要认证                    │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【浏览记录的应用场景】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  1. 个人历史记录：用户可以查看自己浏览过的文章                          │
// │  2. 推荐系统基础：根据浏览历史推荐相关内容                              │
// │  3. 数据分析：统计文章热度、用户活跃度                                  │
// │  4. 阅读续传：记住用户阅读到哪篇文章                                    │
// │                                                                         │
// │  【隐私考虑】                                                            │
// │  - 浏览记录属于敏感数据，需要权限控制                                   │
// │  - 提供删除功能，用户可以清除历史                                       │
// │  - 可以设置自动过期时间                                                 │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 浏览记录如何去重？
// A: 可以在保存前检查是否已存在相同记录，
//    如果存在则更新 viewedAt 时间，而不是新建记录。
// 
// Q2: 如何防止浏览记录表过大？
// A: 1. 设置 TTL 索引自动删除过期记录
//    2. 限制每个用户最大记录数
//    3. 定期清理旧数据
// 
// Q3: 浏览记录和收藏有什么区别？
// A: 浏览记录是自动记录的，用户被动产生；
//    收藏是用户主动操作，表示对内容感兴趣。
// ============================================================

// ============================================================
// 模块导入
// ============================================================

// 导入 express 框架
const express = require('express');

// 导入浏览记录控制器
// 控制器处理浏览记录的业务逻辑
const browseHistoryController = require('../controllers/browseHistoryController');

// 导入认证中间件
// 用于验证用户身份
const { authMiddleware } = require('../middlewares/auth');

// 创建路由器实例
const router = express.Router();

// ============================================================
// 路由级中间件
// ============================================================

// 应用认证中间件到所有路由
// 这意味着下面定义的所有路由都需要先通过认证
// 
// 【工作原理】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │   请求进入                                                              │
// │       │                                                                 │
// │       ▼                                                                 │
// │   authMiddleware                                                        │
// │       │                                                                 │
// │       ├── 验证 token 有效？                                             │
// │       │     ├── 是 → next() → 继续到路由处理函数                        │
// │       │     └── 否 → 返回 401 未授权                                    │
// │       │                                                                 │
// │       ▼                                                                 │
// │   路由处理函数                                                          │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【优点】
// 1. 不需要在每个路由单独添加 authMiddleware
// 2. 代码更简洁，避免重复
// 3. 确保所有路由都被保护，不会遗漏
router.use(authMiddleware);

// ============================================================
// 路由定义
// ============================================================

// ------------------------------------------------------------
// 添加浏览记录
// ------------------------------------------------------------
// 路由: POST /api/browse-history
// 功能: 记录用户浏览了一篇文章
// 认证: 需要登录（通过 router.use 已应用）
// 
// 【请求示例】
// POST /api/browse-history
// Headers: { Authorization: Bearer <token> }
// Body: {
//   blogId: '507f1f77bcf86cd799439011',  // 文章ID
//   duration: 120  // 停留时长（秒），可选
// }
// 
// 【响应示例】
// {
//   success: true,
//   message: '浏览记录已保存'
// }
// 
// 【业务逻辑】
// 1. 从 token 获取当前用户ID
// 2. 检查是否已存在该文章的浏览记录
//    - 存在：更新 viewedAt 时间
//    - 不存在：创建新记录
// 3. 返回成功响应
// 
// 【何时调用？】
// - 用户打开文章详情页时
// - 可以在页面加载后异步调用，不阻塞内容显示
router.post('/', browseHistoryController.addHistory);

// ------------------------------------------------------------
// 获取浏览历史
// ------------------------------------------------------------
// 路由: GET /api/browse-history
// 功能: 获取当前用户的浏览历史列表
// 认证: 需要登录（通过 router.use 已应用）
// 
// 【请求示例】
// GET /api/browse-history?page=1&limit=20
// Headers: { Authorization: Bearer <token> }
// 
// 【查询参数】
// - page: 页码，默认为1
// - limit: 每页数量，默认为20
// 
// 【响应示例】
// {
//   success: true,
//   data: {
//     history: [
//       {
//         _id: '...',
//         blog: {
//           _id: '...',
//           title: '文章标题',
//           author: { username: '...' }
//         },
//         viewedAt: '2024-01-01T12:00:00.000Z'
//       }
//     ],
//     total: 100
//   }
// }
// 
// 【数据排序】
// 通常按浏览时间倒序排列（最近浏览的在前）
// .sort({ viewedAt: -1 })
// 
// 【数据关联】
// 使用 populate 关联查询文章详情
// .populate('blog', 'title author coverImage')
router.get('/', browseHistoryController.getHistory);

// ------------------------------------------------------------
// 清空浏览历史
// ------------------------------------------------------------
// 路由: DELETE /api/browse-history
// 功能: 清空当前用户的所有浏览记录
// 认证: 需要登录（通过 router.use 已应用）
// 
// 【请求示例】
// DELETE /api/browse-history
// Headers: { Authorization: Bearer <token> }
// 
// 【响应示例】
// {
//   success: true,
//   message: '浏览历史已清空',
//   data: { deletedCount: 50 }
// }
// 
// 【业务逻辑】
// 1. 获取当前用户ID
// 2. 删除该用户的所有浏览记录
//    BrowseHistory.deleteMany({ user: userId })
// 3. 返回删除数量
// 
// 【安全考虑】
// 只能删除自己的浏览记录
// 不能删除其他用户的记录
router.delete('/', browseHistoryController.clearHistory);

// ============================================================
// 导出路由
// ============================================================
// 将路由模块导出，供 index.js 中挂载使用
// 使用方式：app.use('/api/browse-history', require('./browseHistoryRoutes'))
module.exports = router;
