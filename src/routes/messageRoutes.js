// ============================================================
// messageRoutes.js - 私信路由
// ============================================================
// 
// 【文件职责】
// 定义私信相关的 API 路由，包括：
// 1. 获取联系人列表
// 2. 获取消息历史
// 3. 发送消息
// 4. 上传附件
// 5. 标记已读
// 6. 分享博客
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. 所有路由都需要认证：私信是私密通信                                  │
// │  2. 文件上传：使用 multer 中间件处理                                    │
// │  3. 与 WebSocket 配合：HTTP 发送 + WebSocket 推送                       │
// │  4. RESTful 设计：资源导向的路由设计                                    │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【路由表】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  方法   │ 路径              │ 认证  │ 功能                             │
// │  ──────┼───────────────────┼───────┼─────────────────────────────────│
// │  GET    │ /contacts         │ 是    │ 获取联系人列表                   │
// │  GET    │ /:userId          │ 是    │ 获取与某用户的消息历史           │
// │  POST   │ /                 │ 是    │ 发送新消息                       │
// │  POST   │ /upload           │ 是    │ 上传消息附件                     │
// │  PUT    │ /read             │ 是    │ 标记消息已读                     │
// │  DELETE │ /:id              │ 是    │ 删除消息                         │
// │  POST   │ /share            │ 是    │ 分享博客给好友                   │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【HTTP + WebSocket 混合架构】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   【发送消息流程】                                                        │
// │   ─────────────                                                        │
// │                                                                         │
// │   客户端 A                                                              │
// │   ────────                                                              │
// │       │                                                                 │
// │       │ 1. POST /messages (HTTP)                                       │
// │       │    { receiver: B_id, content: "你好" }                         │
// │       ▼                                                                 │
// │   服务器                                                                 │
// │   ──────                                                                │
// │       │                                                                 │
// │       ├── 2. 保存消息到数据库                                           │
// │       │    Message.create({...})                                        │
// │       │                                                                 │
// │       ├── 3. 通过 WebSocket 推送给 B                                    │
// │       │    socketService.sendMessage(B_id, {...})                      │
// │       │                                                                 │
// │       ▼                                                                 │
// │   客户端 B                                                              │
// │   ────────                                                              │
// │       │                                                                 │
// │       │ 4. 收到实时消息                                                 │
// │       │    socket.on('newMessage', ...)                                │
// │       ▼                                                                 │
// │   显示消息                                                              │
// │                                                                         │
// │   【为什么用 HTTP 发送？】                                                │
// │   - HTTP 可靠：消息一定会保存到数据库                                   │
// │   - WebSocket 推送：让接收方实时收到                                    │
// │   - 两者结合：既可靠又实时                                              │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么所有路由都需要认证？
// A: 私信是私密通信，必须验证用户身份
// 
// Q2: 如何处理离线消息？
// A: 消息保存到数据库，用户上线后通过 HTTP 获取历史
// 
// Q3: 文件上传如何处理？
// A: multer 中间件处理 multipart/form-data
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================
const express = require('express');
const router = express.Router();
const messageController = require('../controllers/messageController');
const { authMiddleware } = require('../middlewares/auth');
const uploadService = require('../services/uploadService');

// ============================================================
// 联系人相关路由
// ============================================================

// ========================================================
// GET /contacts - 获取联系人列表
// ========================================================
// 【需要认证】authMiddleware
// 
// 【响应】
// [
//   {
//     user: { _id, username, avatar },
//     lastMessage: { content, createdAt },
//     unreadCount: 3
//   },
//   ...
// ]
// 
// 【实现逻辑】
// 1. 查询与当前用户有消息往来的所有用户
// 2. 获取每个用户的最后一条消息
// 3. 统计未读消息数
// 4. 按最后消息时间排序
// ========================================================
router.get('/contacts', authMiddleware, messageController.getContacts);

// ============================================================
// 消息相关路由
// ============================================================

// ========================================================
// GET /:userId - 获取与特定用户的消息历史
// ========================================================
// 【需要认证】authMiddleware
// 【参数】userId - 对方用户 ID
// 
// 【查询参数】
// ?page=1&limit=20
// 
// 【响应】
// {
//   messages: [...],
//   user: { _id, username, avatar },
//   hasMore: true
// }
// 
// 【实现逻辑】
// 1. 查询 sender=我 AND receiver=对方
// 2. 查询 sender=对方 AND receiver=我
// 3. 合并并按时间排序
// 4. 分页返回
// ========================================================
router.get('/:userId', authMiddleware, messageController.getMessageHistory);

// ========================================================
// POST / - 发送新消息
// ========================================================
// 【需要认证】authMiddleware
// 
// 【请求体】
// {
//   receiver: "接收者ID",
//   content: "消息内容",
//   type: "text" | "image" | "file"
// }
// 
// 【响应】
// {
//   _id: "消息ID",
//   sender: {...},
//   receiver: {...},
//   content: "消息内容",
//   createdAt: "2024-01-01"
// }
// 
// 【实现流程】
// 1. 验证接收者存在
// 2. 创建消息记录
// 3. 通过 WebSocket 推送给接收者
// 4. 返回消息信息
// ========================================================
router.post('/', authMiddleware, messageController.sendMessage);

// ========================================================
// POST /upload - 上传消息附件
// ========================================================
// 【需要认证】authMiddleware
// 
// 【中间件】uploadService.singleUpload('image')
// - 处理 multipart/form-data
// - 限制文件大小和类型
// - 保存到指定目录
// 
// 【请求】multipart/form-data
// - image: 文件
// 
// 【响应】
// {
//   url: "/uploads/xxx.jpg",
//   filename: "xxx.jpg"
// }
// ========================================================
router.post('/upload', authMiddleware, uploadService.singleUpload('image'), messageController.uploadAttachment);

// ========================================================
// PUT /read - 标记消息为已读
// ========================================================
// 【需要认证】authMiddleware
// 
// 【请求体】
// {
//   senderId: "发送者ID"
// }
// 
// 【实现】
// 将所有来自该发送者的未读消息标记为已读
// Message.updateMany(
//   { sender: senderId, receiver: me, status: 'unread' },
//   { status: 'read', readAt: new Date() }
// )
// ========================================================
router.put('/read', authMiddleware, messageController.markAsRead);

// ========================================================
// DELETE /:id - 删除消息
// ========================================================
// 【需要认证】authMiddleware
// 【参数】id - 消息 ID
// 
// 【权限检查】只能删除自己发送或接收的消息
// 【实现】软删除或硬删除
// ========================================================
router.delete('/:id', authMiddleware, messageController.deleteMessage);

// ============================================================
// 分享功能路由
// ============================================================

// ========================================================
// POST /share - 分享博客给好友
// ========================================================
// 【需要认证】authMiddleware
// 
// 【请求体】
// {
//   receiverId: "接收者ID",
//   blogId: "博客ID"
// }
// 
// 【响应】
// {
//   message: "分享成功",
//   data: { 消息信息 }
// }
// 
// 【实现】
// 1. 获取博客信息
// 2. 创建分享消息
// 3. 通过 WebSocket 推送
// ========================================================
router.post('/share', authMiddleware, messageController.shareBlog);

// ============================================================
// 导出路由
// ============================================================
// 【挂载方式】在 index.js 中：
// router.use('/messages', messageRoutes);
// 
// 【最终路径示例】
// GET  /messages/contacts     → 联系人列表
// GET  /messages/:userId      → 消息历史
// POST /messages              → 发送消息
// POST /messages/upload       → 上传附件
// PUT  /messages/read         → 标记已读
// ============================================================
module.exports = router;
