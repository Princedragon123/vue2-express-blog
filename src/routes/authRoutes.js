// ============================================================
// authRoutes.js - 认证路由
// ============================================================
// 
// 【文件职责】
// 定义用户认证相关的 API 路由，包括：
// 1. 用户注册
// 2. 用户登录
// 3. 获取当前用户信息
// 4. 用户登出
// 5. Token 刷新
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. Express Router：模块化路由管理                                      │
// │  2. 路由中间件：authMiddleware 保护需要认证的路由                       │
// │  3. RESTful 设计：POST 创建、GET 读取、DELETE 删除                      │
// │  4. 路由前缀：在 index.js 中设置 /auth 前缀                             │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【路由表】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  方法   │ 路径              │ 中间件      │ 功能                       │
// │  ──────┼───────────────────┼─────────────┼───────────────────────────│
// │  POST   │ /register         │ 无          │ 用户注册                   │
// │  POST   │ /login            │ 无          │ 用户登录                   │
// │  GET    │ /me               │ auth        │ 获取当前用户信息           │
// │  POST   │ /logout           │ auth        │ 用户登出                   │
// │  POST   │ /refresh-token    │ 无          │ 刷新 Token                 │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【认证流程】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   【登录流程】                                                           │
// │   ──────────                                                           │
// │   客户端 ──POST /auth/login──> 服务器                                   │
// │                              │                                          │
// │                              ├── 验证用户名密码                          │
// │                              ├── 生成 JWT Token                         │
// │                              └── 返回 Token + 用户信息                   │
// │                                                                         │
// │   【访问受保护资源】                                                      │
// │   ────────────────                                                      │
// │   客户端 ──GET /auth/me──> 服务器                                        │
// │          (Header: Authorization: Bearer <token>)                        │
// │                              │                                          │
// │                              ├── authMiddleware 验证 Token              │
// │                              │   ├── 解析 Token                         │
// │                              │   ├── 验证有效性                         │
// │                              │   └── 提取用户信息到 req.user            │
// │                              │                                          │
// │                              └── 控制器处理请求                          │
// │                                                                         │
// │   【Token 刷新】                                                         │
// │   ────────────                                                          │
// │   客户端 ──POST /auth/refresh-token──> 服务器                            │
// │          (Header: Authorization: Bearer <old_token>)                    │
// │                              │                                          │
// │                              ├── 验证旧 Token（允许过期）                │
// │                              ├── 生成新 Token                           │
// │                              └── 返回新 Token                           │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么登录不需要 authMiddleware？
// A: 因为登录时用户还没有 Token，需要先验证密码再生成 Token
// 
// Q2: Token 刷新为什么不放在 authMiddleware 后面？
// A: 刷新时旧 Token 可能已过期，需要特殊处理
// 
// Q3: 如何实现"记住我"功能？
// A: 登录时根据 rememberMe 参数选择不同的 Token 过期时间
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================

// Express 框架
const express = require('express');

// 创建路由实例
// 【Router 是什么？】
// 一个迷你应用，可以定义路由和中间件
// 最后挂载到主应用上
const router = express.Router();

// 认证控制器
// 【职责】处理认证相关的业务逻辑
const authController = require('../controllers/authController');

// 认证中间件
// 【职责】验证 JWT Token，保护需要登录的路由
// 【用法】router.get('/me', authMiddleware, controller)
// 【效果】只有携带有效 Token 的请求才能通过
const { authMiddleware } = require('../middlewares/auth');

// ============================================================
// 路由定义
// ============================================================

// ========================================================
// POST /register - 用户注册
// ========================================================
// 【请求体】
// {
//   username: "用户名",
//   email: "邮箱",
//   password: "密码"
// }
// 
// 【响应】
// 成功: { user: {...}, token: "jwt_token" }
// 失败: { message: "错误信息" }
// 
// 【不需要认证】注册时用户还没有账号
// ========================================================
router.post('/register', authController.register);

// ========================================================
// POST /login - 用户登录
// ========================================================
// 【请求体】
// {
//   username: "用户名",
//   password: "密码",
//   rememberMe: true/false
// }
// 
// 【响应】
// 成功: { user: {...}, token: "jwt_token" }
// 失败: { message: "用户名或密码错误" }
// 
// 【不需要认证】登录时用户还没有 Token
// ========================================================
router.post('/login', authController.login);

// ========================================================
// GET /me - 获取当前用户信息
// ========================================================
// 【请求头】
// Authorization: Bearer <token>
// 
// 【响应】
// 成功: { user: {...} }
// 失败: { message: "未授权" }
// 
// 【需要认证】authMiddleware 会验证 Token
// 【中间件作用】
// 1. 从 Header 中提取 Token
// 2. 验证 Token 有效性
// 3. 解析用户信息到 req.user
// 4. 如果验证失败，返回 401 错误
// ========================================================
router.get('/me', authMiddleware, authController.getMe);

// ========================================================
// POST /logout - 用户登出
// ========================================================
// 【请求头】
// Authorization: Bearer <token>
// 
// 【响应】
// 成功: { message: "登出成功" }
// 
// 【需要认证】需要知道是谁在登出
// 【实现方式】
// - 服务端：将 Token 加入黑名单（可选）
// - 客户端：删除本地存储的 Token
// ========================================================
router.post('/logout', authMiddleware, authController.logout);

// ========================================================
// POST /refresh-token - Token 刷新
// ========================================================
// 【请求头】
// Authorization: Bearer <old_token>
// 
// 【响应】
// 成功: { token: "new_jwt_token" }
// 失败: { message: "Token 无效" }
// 
// 【不需要 authMiddleware】
// 因为旧 Token 可能已过期，需要特殊处理
// 
// 【刷新流程】
// 1. 客户端检测到 Token 快过期
// 2. 发送 refresh-token 请求
// 3. 服务端验证旧 Token（允许过期）
// 4. 生成新 Token 返回
// ========================================================
router.post('/refresh-token', authController.refreshToken);

// ============================================================
// 导出路由
// ============================================================
// 【挂载方式】在 index.js 中：
// router.use('/auth', authRoutes);
// 
// 【最终路径】
// /auth/register
// /auth/login
// /auth/me
// /auth/logout
// /auth/refresh-token
// ============================================================
module.exports = router;
