// 2. 使用 Mongoose 连接数据库
// 3. 处理连接成功/失败的回调
// 
// 【学习重点】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  1. Mongoose：MongoDB 的 ODM（对象文档映射）                            │
// │  2. 环境变量：敏感信息不硬编码在代码中                                  │
// │  3. async/await：异步连接的优雅写法                                     │
// │  4. 错误处理：连接失败时的退出策略                                      │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【MongoDB 连接流程】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │   服务器启动                                                            │
// │   ────────                                                              │
// │       │                                                                 │
// │       │ server.js                                                       │
// │       ▼                                                                 │
// │   加载环境变量                                                          │
// │   ────────────                                                          │
// │       │                                                                 │
// │       │ require('dotenv').config()                                     │
// │       │ 从 .env 文件读取 MONGODB_URI                                   │
// │       ▼                                                                 │
// │   调用 connectDB()                                                      │
// │   ────────────────                                                      │
// │       │                                                                 │
// │       │ mongoose.connect(mongoURI)                                     │
// │       │                                                                 │
// │       ├─── 成功 ──→ console.log('连接成功')                            │
// │       │                                                                 │
// │       └─── 失败 ──→ console.error('连接失败')                          │
// │                     process.exit(1)  // 退出进程                        │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【Mongoose 连接选项说明】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【旧版本选项（已弃用）】                                                 │
// │  mongoose.connect(uri, {                                                │
// │    useNewUrlParser: true,      // 使用新的 URL 解析器                   │
// │    useUnifiedTopology: true,   // 使用新的拓扑引擎                      │
// │    useCreateIndex: true,       // 使用 createIndex 创建索引             │
// │    useFindAndModify: false     // 禁用 findAndModify                    │
// │  })                                                                     │
// │                                                                         │
// │  【新版本（Mongoose 6+）】                                               │
// │  以上选项默认启用，无需手动配置                                          │
// │  mongoose.connect(uri)  // 简单写法                                     │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【连接字符串格式】
// ┌─────────────────────────────────────────────────────────────────────────┐
// │                                                                         │
// │  【本地开发】                                                            │
// │  mongodb://localhost:27017/blog_db                                     │
// │  ├── mongodb://     - 协议                                              │
// │  ├── localhost      - 主机名                                            │
// │  ├── 27017          - 端口号                                            │
// │  └── blog_db        - 数据库名                                          │
// │                                                                         │
// │  【生产环境（带认证）】                                                   │
// │  mongodb://username:password@host:port/database?options                │
// │  ├── username        - 用户名                                           │
// │  ├── password        - 密码                                             │
// │  ├── host            - 服务器地址                                       │
// │  ├── port            - 端口号                                           │
// │  ├── database        - 数据库名                                         │
// │  └── options         - 连接选项                                         │
// │                                                                         │
// │  【MongoDB Atlas（云服务）】                                             │
// │  mongodb+srv://username:password@cluster.mongodb.net/database          │
// │  └── mongodb+srv://  - 使用 SRV 记录自动发现节点                        │
// │                                                                         │
// └─────────────────────────────────────────────────────────────────────────┘
// 
// 【面试常问】
// Q1: 为什么用 Mongoose 而不是原生 MongoDB 驱动？
// A: Mongoose 提供 Schema 验证、中间件、关联查询等功能
// 
// Q2: 连接失败时为什么要退出进程？
// A: 数据库连接失败意味着应用无法正常工作，不如直接退出
// 
// Q3: 如何处理数据库断开连接？
// A: 监听 disconnected 事件，实现自动重连
// ============================================================

// ============================================================
// 导入依赖模块
// ============================================================

// Mongoose：MongoDB 对象建模工具
// 【作用】
// - 定义 Schema（数据结构）
// - 创建 Model（数据模型）
// - 提供中间件和验证
const mongoose = require('mongoose');

// dotenv：环境变量管理
// 【作用】从 .env 文件加载环境变量到 process.env
// 【好处】敏感信息不硬编码在代码中
require('dotenv').config();

// ============================================================
// 获取数据库连接字符串
// ============================================================
// 【来源】.env 文件中的 MONGODB_URI
// 【示例】MONGODB_URI=mongodb://localhost:27017/blog_db
// 
// 【安全提示】
// - 不要将 .env 文件提交到 Git
// - 生产环境使用环境变量或密钥管理服务
// ============================================================
const mongoURI = process.env.MONGODB_URI;

// ============================================================
// 连接 MongoDB 数据库
// ============================================================
// 【async/await】异步函数，等待连接完成
// 【导出】供 server.js 调用
// ============================================================
const connectDB = async () => {
    try {
        // ====================================================
        // 连接 MongoDB
        // ====================================================
        // mongoose.connect() 返回 Promise
        // Mongoose 6+ 默认启用所有推荐选项
        await mongoose.connect(mongoURI);
        
        // ====================================================
        // 连接成功
        // ====================================================
        console.log('MongoDB 数据库连接成功');
    } catch (error) {
        // ====================================================
        // 连接失败
        // ====================================================
        // 输出错误信息
        console.error('MongoDB 数据库连接失败:', error.message);
        
        // 退出进程
        // process.exit(1) - 非零退出码表示异常退出
        // process.exit(0) - 零退出码表示正常退出
        process.exit(1);
    }
};

// ============================================================
